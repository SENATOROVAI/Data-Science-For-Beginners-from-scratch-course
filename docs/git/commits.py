"""Commit descriptions."""

# Опишите своими словами назначение каждого из этих типов коммитов:
# feat - добавление новой функциональности в проект.
#
# fix - исправление ошибки или бага в существующей функциональности.
#
# docs - добавление, удаление или изменение документации без изменения логики
# программы.
#
# style - корректировка форматирования и оформления кода: отступов, пробелов,
# переносов строк, порядка импортов и других элементов, не влияющих на его
# поведение.
#
# refactor - изменение внутренней структуры кода для повышения читаемости,
# компактности, поддерживаемости или улучшения алгоритма без изменения внешнего
# поведения программы.
#
# test - добавление, изменение или исправление модульных, интеграционных,
# сквозных и других автоматизированных тестов.
#
# build - изменения системы сборки проекта, зависимостей, пакетных менеджеров,
# Dockerfile, Makefile и других средств подготовки приложения к запуску или
# публикации.
#
# ci - изменения процессов непрерывной интеграции и доставки: конфигураций
# GitHub Actions, GitLab CI, Jenkins и других CI/CD-инструментов.
#
# perf - изменение кода, направленное на повышение производительности, снижение
# потребления памяти или улучшение асимптотической сложности без изменения
# функциональности.
#
# chore - вспомогательные технические изменения, не добавляющие
# функциональность и не исправляющие конкретный баг: обновление зависимостей,
# удаление неиспользуемых библиотек, модулей, переменных, служебных файлов и
# настройка конфигурации проекта.
# =======================================================
#
# Представьте, что вы исправили баг в функции, которая некорректно округляет
# числа. Сделайте фиктивный коммит и напишите для него сообщение в соответствии
# с Conventional Commits (используя тип fix).
#  git commit -m 'fix: correct rounding of numbers'
# =======================================================
#
# Добавление новой функциональности:
# Допустим, вы реализовали новую функцию generateReport в проекте. Сделайте
# фиктивный коммит с типом feat, отражающий добавление этой функциональности
#  git commit -m 'feat: add new function generateReport'
# =======================================================
#
# Модификация формата кода или стилей:
# Представьте, что вы поправили отступы и форматирование во всём проекте, не
# меняя логики кода. Сделайте фиктивный коммит с типом style
#  git commit -m 'style: fix indents across the project'
# =======================================================
#
# Документация и тестирование:
#
# Сделайте фиктивный коммит с типом docs, добавляющий или улучшающий
# документацию для вашей новой функции.
#  git commit -m 'docs: add instructions for generateReport function'
#
# Сделайте фиктивный коммит с типом test, добавляющий тесты для этой же
# функции.
#  git commit -m 'test: add tests for generateReport function'
