#
# Да, можно. Если вы спрятали свои изменения в stash,
# рабочая директория становится чистой,
# и git pull может быть выполнен без конфликтов.
#
# 26.1. Что может произойти, если восстановить stash после принятия pull?
#
# После git pull в файле появятся изменения из удалённого репозитория.
# Когда вы восстановите stash (git stash pop),
# Git попытается применить ваши спрятанные изменения поверх обновлённого файла.
# Может возникнуть конфликт, если изменения затрагивают
# одни и те же строки.
# В этом случае конфликт придётся разрешать вручную.
