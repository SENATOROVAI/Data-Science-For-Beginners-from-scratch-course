# **4. Какие способы переноса строк показаны в видео?**

# Шесть способов. Рекомендованный PEP 8 способ — неявное продолжение строки внутри круглых скобок (4.4, 4.5); обратный слэш (4.1) работает, но не рекомендуется.

# **4.1. Обратный слэш (\\):**
#
# ```python
# string_continued = "This is a long string that we want to " \
#                    "split across multiple lines."
# print(string_continued)
# ```

# `\` в конце строки говорит интерпретатору, что инструкция продолжается на следующей строке; две строки-литерала рядом склеиваются в одну. Минус: после `\` не должно быть даже пробела, иначе ошибка; PEP 8 рекомендует вместо этого скобки.

# **4.2. Тройные кавычки (''' или """):**
#
# ```python
# multi_line_string = """This is a string that spans
# multiple lines. You can write freely
# and it will keep the line breaks."""
# print(multi_line_string)
# ```

# Строка в тройных кавычках может занимать несколько строк, и переносы строк сохраняются внутри самой строки (в ней будут символы `\n`). Подходит для многострочного текста и docstring, но не для «разбиения» одной длинной строки без переносов.

# **4.3. Список строк, объединённый через join:**
#
# ```python
# strings = [
#     "This is the first line.",
#     "This is the second line.",
#     "This is the third line.",
# ]
# result = "\n".join(strings)  # объединяем через перенос строки '\n'
# print(result)
# ```

# Строки хранятся в списке, а метод `str.join` склеивает их через разделитель — здесь `\n`, поэтому каждая выводится с новой строки. Удобно, когда строк много или они формируются программно.

# **4.4. Круглые скобки для продолжения строки:**
#
# ```python
# long_string = (
#     "This is a very long string that I would like to "
#     "continue on the next line."
# )
# print(long_string)
# ```

# Внутри круглых скобок Python позволяет переносить строки без `\`, а соседние строковые литералы автоматически склеиваются в одну строку (без символа переноса). Это способ, рекомендованный PEP 8.

# **4.5. f-строки в круглых скобках:**
#
# ```python
# letter_a = 5
# letter_b = 6
# product_ab = letter_a * letter_b
#
# message = (
#     f"when {letter_a} is multiplied by {letter_b}, "
#     f"the result is {product_ab}"
# )
# print(message)
# ```

# То же, что 4.4, но с f-строками: в каждую часть подставляются значения переменных в `{}`. Каждая часть, где есть подстановка, должна иметь свой префикс `f`.

# **4.6. Конкатенация строк через +:**
#
# ```python
# string_part1 = "This is the first part, "
# string_part2 = "and this is the second part."
# full_string = string_part1 + string_part2
# print(full_string)
# ```

# Оператор `+` склеивает строки (в том числе хранящиеся в переменных). Подходит для небольшого числа строк; для объединения многих строк эффективнее `join`, а для подстановки значений — f-строки.

