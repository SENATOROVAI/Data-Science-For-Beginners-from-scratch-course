# ## Основные вопросы

# **1. Зачем нужна кнопка History и какие функции появляются при нажатии правой кнопкой мыши на коммит?**

# Вкладка **History** в GitHub Desktop показывает историю коммитов текущей ветки: кто, когда и что изменил. Если выбрать коммит, справа видно список изменённых файлов и сами изменения (diff): зелёным добавленные строки, красным удалённые.
#
# По правому клику на коммит доступны:
# - **Amend commit** — исправить последний коммит (сообщение или содержимое), если он ещё не отправлен;
# - **Reset to commit** — откатить ветку к этому коммиту;
# - **Revert changes in commit** — создать новый коммит, отменяющий изменения выбранного;
# - **Create branch from commit** — создать ветку от этого коммита;
# - **Create tag** — поставить тег (например, версию);
# - **Cherry-pick commit** — перенести коммит в другую ветку;
# - **Copy SHA** — скопировать хеш коммита;
# - **Copy tag** — скопировать тег;
# - **View on GitHub** — открыть коммит на сайте GitHub.

# **1.1. Где взять ссылку на коммит? Куда её отправлять?**

# Правый клик по коммиту в History → **View on GitHub**. Откроется страница коммита в браузере, ссылку копируем из адресной строки. Она имеет вид `https://github.com/<user>/<repo>/commit/<SHA>`.
#
# Ссылку на коммит отправляем проверяющему, туда, где сдаётся задание (форма или чат сдачи ДЗ курса), чтобы он увидел конкретно то, что сделано.

# **2. Что такое файл лога?**

# Файл лога (`log`) — это рабочий журнал. В нём записывается, что сделано на уроке: что изучено, какие задания выполнены, какие ошибки возникли и как они решены, какие остались вопросы. Это позволяет проверяющему и самому студенту видеть прогресс.

# **2.1. Когда нужно его пушить?**

# В конце каждого урока (рабочего дня), после того как в него внесены записи о проделанной работе. Коммит с логом отправляется на GitHub вместе с выполненными заданиями.

# **3. Что такое интерпретатор?**

# Интерпретатор — это программа, которая читает код на Python и выполняет его построчно (без предварительной компиляции всего кода в машинный). Для Python стандартный интерпретатор — CPython, на Windows это файл `python.exe`. У каждого интерпретатора своя версия Python и свой набор установленных пакетов, поэтому важно выбрать правильный.

# **4. Где можно выбрать интерпретатор?**

# - В VS Code для `.py` файлов: в правом нижнем углу строки состояния (там написана версия Python) или через `Ctrl+Shift+P` → **Python: Select Interpreter**.
# - Для ноутбуков `.ipynb`: кнопка **Select Kernel** в правом верхнем углу ноутбука.

# **5. Что такое модуль?**

# Модуль — это файл с кодом Python (`.py`), который можно импортировать в другой код командой `import`. В модуле лежат функции, классы и переменные. Несколько модулей, собранных в папку, образуют пакет. Пример стандартного модуля: `import math`.

# **6. Как создать и отправить коммит?**

# В GitHub Desktop:
# 1. На вкладке **Changes** отметить нужные файлы.
# 2. Внизу слева написать сообщение коммита (Summary), например `docs: add git quiz`.
# 3. Нажать **Commit to <ветка>**.
# 4. Нажать **Push origin** вверху.
#
# В VS Code: вкладка **Source Control** (`Ctrl+Shift+G`) → нажать `+` у файлов → ввести сообщение → **Commit** → **Sync Changes**.
#
# Через терминал:
# ```bash
# git add .
# git commit -m "docs: add git quiz"
# git push
# ```

# **7. Как убедиться, что коммит отправлен и находится на GitHub?**

# - В GitHub Desktop кнопка вверху показывает **Fetch origin** без стрелки с числом (если есть ↑1, коммит ещё не отправлен).
# - `git status` пишет `Your branch is up to date with 'origin/<ветка>'`.
# - На сайте GitHub в репозитории, в нужной ветке, коммит виден в списке **Commits**.

# **8. Какая команда показывает, что код не прошёл проверки на ошибки?**

# ```bash
# pre-commit run --all-files
# ```
# Она запускает все проверки из `.pre-commit-config.yaml`. Напротив каждой проверки пишется `Passed`, `Failed` или `Skipped`. Если есть хотя бы один `Failed`, код не прошёл проверку. Те же проверки запускаются автоматически при `git commit`.

# **8.1. Перечислите линтеры, которые используются для проверки кода, и кратко охарактеризуйте каждый.**

# - **Ruff** — быстрый линтер и форматер. Заменяет flake8, pep8-naming, pydocstyle, isort, pyupgrade и black: проверяет стиль PEP 8, имена, docstring, порядок импортов, современный синтаксис, форматирует код.
# - **black** — форматер: приводит код к единому стилю автоматически.
# - **isort** — сортирует и группирует импорты.
# - **flake8** — проверяет стиль PEP 8 и ошибки (неиспользуемые переменные и т.п.); в курсе с плагинами, которые запрещают однобуквенные имена переменных (VNE001) и требуют понятных имён функций.
# - **pylint** — глубокий анализ кода: ошибки, плохие практики, дублирование, сложность.
# - **mypy** — проверка типов (аннотаций типов).
# - **pydocstyle** — проверка оформления docstring (описаний модулей, функций, классов).
# - **pyupgrade** — переписывает код на современный синтаксис Python.
# - **docformatter** — форматирует docstring.
# - **codespell** — ищет опечатки в английских словах.
# - **nbQA** — позволяет запускать эти линтеры на Jupyter-ноутбуках.
# - **jupytext** — создаёт `.py`-копию каждого ноутбука.

# **9. Как узнать, какой именно линтер не прошёл проверку?**

# В выводе `pre-commit run --all-files` строка с названием линтера помечена `Failed`. Под ней идёт список ошибок: имя файла, номер ячейки/строки, код ошибки и описание, например `log.ipynb:cell_2:1:1: D100 Missing docstring in public module`. По коду ошибки (`D100`, `C0114`, `E501`) тоже понятно, какому линтеру он принадлежит.

# **10. Видит ли линтер Pylint markdown?**

# Нет. Pylint (через nbQA) проверяет только код в code-ячейках. Markdown-ячейки для него невидимы. Текст в markdown проверяют другие инструменты: например, codespell ищет опечатки, а blacken-docs форматирует блоки кода внутри markdown.

# **11. Могут ли номер ячейки в терминале и номер ячейки в VS Code отличаться? В каком случае?**

# Да, могут. Линтеры через nbQA нумеруют ячейки по-своему (например, учитывают только code-ячейки), а VS Code считает все ячейки подряд, включая markdown. Поэтому если в ноутбуке есть markdown-ячейки, номера отличаются.
#
# Ещё один источник путаницы: в трассировке ошибки при запуске пишется `Cell In[5]` — это номер запуска ячейки (execution count), а не её позиция в ноутбуке.

# **12. Где посмотреть номер ячейки в VS Code?**

# В строке состояния внизу справа, когда ячейка выбрана: `Cell 5 of 20`. Также ячейки и их порядок видны в панели **Outline**, а слева от code-ячейки отображается номер выполнения `[5]`.

# **13. В каком формате .ipynb отправляется на GitHub? При чём здесь JSON?**

# Файл `.ipynb` — это текстовый файл в формате **JSON**. Внутри: список ячеек (`cells`), у каждой тип (`code`/`markdown`), исходный текст (`source`), результаты выполнения (`outputs`) и метаданные. На GitHub уходит именно этот JSON. Поэтому diff ноутбуков трудно читать, и поэтому линтерам нужна прослойка nbQA, а для проверки рядом создаётся `.py`-копия через jupytext.

# **14. Где посмотреть, в какой ячейке ошибка?**

# - В выводе линтера в терминале: `file.ipynb:cell_3:5:1` означает ячейку 3, строку 5, столбец 1.
# - Если ошибка при выполнении — в трассировке под ячейкой (`Cell In[3], line 5`), а после **Run All** кнопка **Go To** переходит к упавшей ячейке.
# - В панели **Problems** (`Ctrl+Shift+M`).

# **15. Как запустить терминал?**

# В VS Code: меню **View → Terminal** или сочетание `` Ctrl+` ``. Новый терминал — `` Ctrl+Shift+` ``. Вне VS Code: `Win+R` → `cmd` или PowerShell.

# **16. Что такое линтер?**

# Линтер — программа для статического анализа кода: она проверяет код без его запуска и находит ошибки, опечатки, нарушения стиля (PEP 8), подозрительные конструкции и плохие практики. Линтеры помогают держать код единообразным и читаемым.

# **17. На какой сайт нужно вставлять код ошибки, если она связана с Pylint?**

# В документацию Pylint, раздел сообщений: https://pylint.readthedocs.io/en/stable/user_guide/messages/messages_overview.html. Там для каждого кода (например, `C0114 missing-module-docstring`) есть описание, пример неправильного и правильного кода.

# **18. Секция pydocstyle в большинстве случаев закрывается автоматически после исправления ошибок в каком линтере?**

# После исправления ошибок **flake8**: в нём через плагин flake8-docstrings проверяются те же правила docstring (коды `D...`), что и в pydocstyle. Сейчас эти правила объединены в Ruff (группа `D`), поэтому при исправлении ошибок Ruff ошибки pydocstyle исчезают тоже.

# **19. Что такое описание модуля? Должно ли оно отражать содержимое модуля?**

# Описание модуля (module docstring) — строка в тройных кавычках в самом начале файла (в ноутбуке — в первой code-ячейке):
# ```python
# """Квизы по Git и VS Code."""
# ```
# Да, оно должно кратко и по делу описывать, что находится в модуле. Без него линтеры выдают ошибку `D100` / `C0114 missing-module-docstring`.

