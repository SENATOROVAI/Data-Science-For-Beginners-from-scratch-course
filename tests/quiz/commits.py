# Задание 3.
# Вопрос 1. Опишите своими словами назначение каждого типа коммитов:
#
# feat - Добавление новой функции или возможности в программу.
# fix - Исправление ошибки (бага) в коде.
# docs - Добавление или изменение документации, например README или инструкций.
# style - Изменение оформления кода без изменения его работы: пробелы, отступы,
# форматирование.
# refactor - Улучшение структуры существующего кода без изменения его поведения.
# test - Добавление или исправление автоматических тестов для проверки кода.
# build - Изменения в сборке проекта, зависимостях и инструментах сборки.
# ci - Изменения в автоматических процессах проверки, тестирования и сборки
# проекта, например GitHub Actions.
# perf - Оптимизация кода для повышения производительности: чтобы программа
# работала быстрее или потребляла меньше ресурсов.
# chore - Вспомогательные технические изменения, которые не добавляют новых
# функций и не исправляют ошибки в работе программы.
#
# Вопрос 1.1. Зачем в описании коммита или пул реквеста ключевое слово Closes,
# Fixes или Resolves? Чем они отличаются по смыслу и что будет,
# если вместо них написать Refs?
# Эти ключевые слова позволяют автоматически закрывать Issue после слияния
# PR в основную ветку проекта.
# Closes - Закрывает задачу.
# Fixes - Указывает, что исправлена ошибка из задачи.
# Resolves - Указывает, что проблема или задача решена.
# Refs - Ссылается на задачу, но не закрывает её автоматически.
#
