# ## 1. GitHub
#
# **1.1. Что такое GitHub?**
#
# GitHub — крупнейший хостинг Git-репозиториев и платформа для совместной разработки. Кроме хранения кода в нём есть issues, pull requests, ревью кода, уведомления, вики, GitHub Actions для CI/CD и управление доступом к проектам.
#
# **1.2. Как GitHub связан с Git?**
#
# Git — распределённая система контроля версий, она работает локально на компьютере. GitHub хранит Git-репозитории на сервере и служит для них удалённым репозиторием (remote): изменения отправляются туда через `git push` и забираются через `git fetch` / `git pull`. Сверху GitHub добавляет веб-интерфейс и инструменты для совместной работы. Без Git GitHub не работает, а Git без GitHub — работает.
#
# **1.3. Чем fork репозитория отличается от его клонирования (clone)?**
#
# - **Fork** — копия чужого репозитория на сервере GitHub в моём аккаунте. В форк у меня есть права на push, и он сохраняет связь с исходным проектом: из него можно открыть pull request в оригинал.
# - **Clone** — локальная копия репозитория (любого: своего, чужого или форка) на моём компьютере со всей историей.
#
# Обычно делают оба шага: сначала fork на GitHub, потом clone форка к себе.
#
# **1.4. Зачем нужны pull request и как они работают?**
#
# Pull request — предложение влить изменения из одной ветки (часто из ветки форка) в другую ветку проекта. Он нужен, чтобы вносить вклад без прав на запись и чтобы изменения проходили обсуждение, ревью и автоматические проверки до попадания в основную ветку.
#
# Как работает: я создаю ветку, делаю коммиты, отправляю ветку на GitHub и открываю PR. Мейнтейнеры комментируют код построчно, CI запускает проверки. Новые коммиты в эту ветку автоматически добавляются в PR. В конце владелец делает merge или закрывает PR.
#
# **1.5. Использует ли GitHub ваш адрес электронной почты для привязки Git-коммитов к вашей учётной записи?**
#
# Да. GitHub сопоставляет email автора в коммите (`git config user.email`) с адресами, добавленными в аккаунт (Settings → Emails). При совпадении коммит показывается с моим логином и аватаркой и засчитывается в мою активность. Если адрес не привязан, коммит к аккаунту не привязывается.
#
# **1.6. Какая команда генерирует SSH-ключ для доступа к репозиторию по SSH? (Рисунок 83)**
#
# `ssh-keygen`, например:
#
# ```bash
# ssh-keygen -t ed25519 -C "your_email@example.com"
# ```
#
# Публичный ключ (`~/.ssh/id_ed25519.pub`) затем добавляется в GitHub: Settings → SSH and GPG keys → New SSH key.

