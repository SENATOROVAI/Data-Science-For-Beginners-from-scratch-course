# 1. Что делает команда python -m venv venv?
# Команда создает виртуальное окружение venv в папке venv.
# 2. Что делает каждая команда в списке ниже?
# pip list — показывает список установленных Python-пакетов.
# pip freeze > requirements.txt — сохраняет список установленных пакетов
#  и их версий в файл requirements.txt.
# pip install -r requirements.txt — устанавливает все пакеты из файла
# requirements.txt указанных версий.
# 3. Что делает каждая команда в списке ниже?
# conda env list — показывает список всех созданных Conda-окружений.
# conda create -n env_name python=3.5 — создаёт новое окружение
# env_name с Python 3.5.
# conda env update -n env_name -f file.yml — обновляет окружение
# на основе зависимостей из файла file.yml.
# conda activate env_name — активирует указанное окружение.
# conda deactivate — деактивирует текущее окружение.
# conda clean -a — очищает кеш Conda: удаляет неиспользуемые архивы
# пакетов, индексный кеш и другие временные файлы.
