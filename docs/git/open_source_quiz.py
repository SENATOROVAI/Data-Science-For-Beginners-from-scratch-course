# # GitHub
#
# 1.1. Что такое GitHub?
# - веб-платформа для хранения Git-репозиториев и совместной разработки ПО. Она
#   представляет инструменты для работы с кодом, Issues, PR, GitHub Actions,
#   Projects, GH Docs
# 1.2. Как GitHub связан с Git?
# - системой контроля версий, при помощи команд git можно управлять удаленными
#   репозиториями в GH: получать изменения из удаленного репо и отправлять в
#   него локальные коммиты.
# 1.3. Чем отличается fork репозитория от его клонирования (clone)?
# - fork - копия чужого репо, созданная УЗ пользователя GH и сохраняющая связь
#   с исходным репо. Clone - создание локальной копии любого удаленного репо на
#   компьютере разработчика.
# 1.4. Зачем нужны и как работают pull requests?
# - PR - это запрос на включение изменений из одной ветки в другую. Он
#   используется для проверки кода, обсуждения изменений и их слияния с
#   основной веткой проекта. Разраб создает отдельную ветку на GH и создаёт PR.
#   Владелец или участники проекта могут проверить код, оставить комментарии,
#   запросить доработку, принять изменения или закрыть PR без слияния.
#
# 1.5. GitHub использует ваш почтовый адрес для привязки ваших Git коммитов к
#      вашей учётной записи?
# - Да. GitHub связывает Git-коммит с учётной записью, если адрес электронной
#   почты, указанный в коммите, добавлен и подтверждён в этой учётной записи.
#   Также можно использовать специальный GitHub-адрес вида noreply.
#
