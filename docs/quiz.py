# **Ответ:** В видео показано два способа переноса длинной строки: 1) если это текст (строка), то записываем части текста в отдельные переменные и потом объединяем их в одну; 2) если это код, то используем круглые скобки и переносим строку внутри них.

# **4.1.** Обратный слэш ( \ ):
#
# ```python
# string_continued = (
#     "This is a long string that we want to " "split across multiple lines."
# )
# print(string_continued)
# ```

# **Ответ:** Обратный слэш `\` в конце строки говорит Python, что строка продолжается на следующей. После `\` не должно быть пробелов. Обе части склеиваются в одну

# **4.2.** Тройные кавычки ( ''' или """ ):
#
# ```python
# multi_line_string = """This is a string that spans
# multiple lines. You can write freely
# and it will keep the line breaks."""
# print(multi_line_string)
# ```

# **Ответ:** Тройные кавычки (три одинарные или три двойные) создают многострочную строку: все переносы строк внутри сохраняются как есть. Вывод печатается на нескольких строках точно так, как написан в коде.

# **4.3.** Список строк, объединённый через join:
#
# ```python
# strings = [
#     "This is the first line.",
#     "This is the second line.",
#     "This is the third line.",
# ]
# result = "\n".join(strings)  # объединяем через перенос строки '\n'
# print(result)
# ```

# **Ответ:** Список строк объединяется методом join: разделитель, который стоит перед .join, вставляется между элементами. Здесь разделитель — перенос строки (`\n`), поэтому три строки печатаются каждая на новой строке.

# **4.4.** Круглые скобки для продолжения строки:
