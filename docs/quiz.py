# 1.1. Что такое GitHub?
#
# GitHub — это онлайн-платформа для хранения Git-репозиториев,
# совместной разработки программного обеспечения, отслеживания ошибок
# и управления проектами.
#
# 1.2. Как GitHub связан с Git?
#
# Git — это распределённая система контроля версий, а GitHub —
# платформа, использующая Git для хранения репозиториев и организации
# совместной работы над кодом.
#
# 1.3. Чем fork репозитория отличается от его клонирования (clone)?
#
# Fork создаёт копию репозитория в нашем аккаунте GitHub, а clone
# скачивает репозиторий на локальный компьютер. Fork позволяет
# независимо развивать проект на GitHub, а clone — работать с ним
# локально.
#
# 1.4. Зачем нужны pull request и как они работают?
#
# Pull request нужен для предложения изменений в репозиторий.
# Разработчик создаёт отдельную ветку, вносит изменения и открывает
# pull request. После проверки и обсуждения изменений владелец
# репозитория может объединить их с основной веткой.
#
# 1.5. Использует ли GitHub ваш адрес электронной почты для привязки
# Git-коммитов к вашей учётной записи?
#
# Да. GitHub сопоставляет адрес электронной почты автора коммита с
# адресами, привязанными к учётной записи. Можно также использовать
# специальный адрес noreply, чтобы не раскрывать личную почту.
#
