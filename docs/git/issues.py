# ## Закрытие и завершение Issues
# Как закрыть Issue вручную?
# - Открыть нужный issue и нажать кнопку CLose Issue в нижнее части страницы.
#
# - Можно ли автоматически закрыть Issue с помощью сообщения в коммите или Pull Request?
# Да, нужно указать ключевое слово и номер issue: Closes #3 добавлем запись в PR, после слияния PR в основнкю ветку Issue закроется автоматом
#
# Как повторно открыть закрытое Issue, если работа ещё не завершена?
# - зайти в Issues и нажать Reopen Issue.
#
# ## Фильтрация и поиск
# Как найти все открытые или закрытые Issues в репозитории?
# - перейти во вкладку Issues репо и выбрать фильтр Open | Closed, использовать строку поиска с запросами is:.
#
# Как использовать фильтры для поиска Issues по меткам, исполнителям или другим критериям?
# - В разделе Issues воспользоваться строкой поиска или меню Filters. Можно фильтровать задачи по меткам, исполнителям, автору, этапу, состоянию.
#
# Как сортировать Issues по приоритету, дате создания или другим параметрам?
# - используя Sort для сортировки задачи по дате создания (Newest, Oldest), дате обновления или кол-ву комментов (Most Commented, Least Commented). Приоритет обычно задают с помощью Labels, Projects или Milestones.
#
# ## Интеграции и автоматизация
# Как настроить автоматические уведомления о новых или изменённых Issues?
# - Нажать кнопку Watch в репо и выбрать режим получения уведомлений (All Activity, Custom, Participating, Ignore). Подписаться на отдельный Issue через Subscribe.
#
# Что такое Projects в контексте GitHub, и как связать их с Issues?
# - таск менеджер и планировщик работы над проектом в виде Kanban доски, таблицы или дорожной карты. Issue можно связывать с проектом через Projects при создании или редактировании Issue либо добавить в проект вручную.
#
# Какие сторонние инструменты можно использовать для автоматизации работы с Issues (например, боты, Webhooks)?
# - GH Actions - автомат выполнение сценариев при создании или изменении Issue
# - Webhooks - оправка событий GH во внешние системы
# - GH Appps и GH Bots (Dependabot, Probot)
# - Системы автоматизации: Zapier, Make (Integromat), IFTTT
# - ПО управления проектами: Jira, Trello, Slack, MS Teams
#
# ## Коллаборация
# Как упомянуть другого пользователя в комментарии к Issue?
# - @ и имя пользователя GitHub
#
# Как запросить дополнительные данные или уточнения у автора Issue?
# - Комментарием в Issue с запросом инфо: шаги воспроизведения, логи, скрины, описание окружения + @
#
# Что делать, если Issue неактуально или его нужно объединить с другим?
# - Закрыть с комментарием или с ссылкой на дублирующий Issue
#
# ## Практические аспекты
# Как использовать шаблоны для создания Issues?
# - В репо создать шаблон в каталоге .github/ISSUE_TEMPLATE и выбрать подходящий при создании Issue
#
# Что такое Linked Issues, и как создать связь между задачами?
# - связанные задачи, отражающие зависимость или логическую связь между Issue при помощи ссылки или номера друго Issue в описании или комментарии или связаь автоматом с PR с помощью ключей Closes, Fixes, Resolves
#
# Какие метрики (например, время выполнения) можно отслеживать с помощью Issues?
# - время создания и закрытия задач
# - количество открытых и закрытых Issue
# - время выполнения (Lead Time)
# - кол-во комментариев и обсуждений
# - загрузку исполнителей
# - прогресс по Milestones и Projects
#
# Какие best practices рекомендуются при работе с Issues в команде?
# - Давать понятные и краткие заголовки
# - Подробно описывать проблему или задачу
# - Использовать Labels, Assignees и Milestones
# - Не создавать дубликаты,а связывать похожие Issues
# - Регулрно обновлять статус и закрывать неактульные задачи
# - Связывать Issue c PR и коммитами
# - Использовать шаблоны Issue для единообразного оформления
