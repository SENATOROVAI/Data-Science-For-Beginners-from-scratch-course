"""Решение квиза по git stash."""

# Основы
# Что делает команда git stash?
# Сохраняет незакоммиченные изменения отслеживаемых (tracked) файлов в стек стэшей
# внутри репозитория и возвращает рабочую директорию к состоянию последнего коммита.
#
# Как просмотреть список всех сохранённых изменений (стэшей)?
# git stash list
#
# Какая команда применяет верхний стэш?
# git stash apply — применяет верхний стэш и оставляет его в списке;
# git stash pop — применяет верхний стэш и удаляет его из списка.
#
# Как применить конкретный стэш по его номеру?
# git stash apply stash@{N}, где N — номер из git stash list
# (или git stash pop stash@{N}, чтобы применить и удалить).
#
# Чем команда git stash apply отличается от git stash pop?
# apply применяет стэш, а pop применяет и удаляет этот стэш
#
# Что делает команда git stash drop?
# удаляет стэш без его применения
#
# Как полностью очистить все сохранённые стэши?
# git stash clear
#
# В каких случаях удобно использовать git stash?
# Рабочую директорию нужно очистить перед pull или merge.
# Срочное переключение на другую ветку или задачу.
# Временное сохранение работы, не готовой к коммиту.
# Тестирование в чистой рабочей директории.
#
# Что произойдёт, если выполнить git stash pop, когда в проекте есть
# конфликтующие изменения?
# При конфликте git stash pop применит доступные изменения, остановится на спорных участках с маркерами конфликта и не удалит запись из stash
#
# Можно ли восстановить стэш, удалённый командой git stash drop?
# Да, восстановить стэш после git stash drop можно, пока сборщик мусора Git (git gc) не удалил соответствующие объекты из локальной базы.
#
# Команды с параметрами
# Что делает команда git stash save "NAME_STASH"?
# сохраняет незакоммиченные изменения в стэш под указанным именем
#
# Что делает команда git stash apply <номер_стэша>?
# применяет стэш с указанным номером
#
# Что делает команда git stash pop <номер_стэша>?
# применяет указанный стэш и удаляет его
