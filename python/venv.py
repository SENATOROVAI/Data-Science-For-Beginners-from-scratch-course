# 13. Зачем нужно виртуальное окружение?
# Виртуальное окружение — это отдельная папка со своим Python
# и своими пакетами нужных версий.
# Оно нужно, чтобы зависимости разных проектов не конфликтовали
# между собой и чтобы проект можно
# было легко воспроизвести на другом компьютере.
