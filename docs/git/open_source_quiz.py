# # Создание запроса на слияние
# 4 Можно ли открыть пул реквест, если вы ничего не вносили в FORK?
# - нет. Pull Request можно открыть только при наличии изменений (коммитов) в
#   вашем fork или ветке по сравнению с веткой исходного репозитория. Без
#   изменений создать Pull Request нельзя.
#
# 4.1 Что нужно сделать чтобы открыть пул реквест? (Рисунок 90)
# ①Клонируем нашу копию
# ②Создаём тематическую ветку
# ③Вносим свои изменения
# ④Проверяем изменения
# ⑤Фиксируем изменения в тематической ветку
# ⑥Отправляем новую ветку в нашу копию на GitHub
# Теперь, если мы зайдём на страничку нашей копии на GitHub, мы увидим, что
# GitHub заметил наши изменения и предлагает открыть запрос на слияние с
# помощью большой зелёной кнопки.
# Также можно зайти на страницу «Branches», по адресу
# https://github.com/<user>/<project>/branches, найти интересующую ветку и
# открыть запрос оттуда
#
# 4.2 Что нужно сделать Если ваш Форк устарел?
# - подтянуть актуальные изменения из исходного репо (upstream) и отправить
#   обновленную ветку в свой fork (origin) Sync fork - Update branch
#
# 4.3 Что нужно сделать если в пул реквесте имеются конфликты слияния (Рисунок
#     96)
# - Если в PR возникли конфликты слияния, необходимо разрешить  их: обновить
#   свою ветку актуальными изменениями из целевой ветки, вручную устранить
#   конфликты в файлах, проверить рез-т, сделать новый коммит и отправить
#   изменения git push. После этого PR обновится автоматически.

