# ### Вопрос 23
#
# **Где увидеть конфликты файлов?**
#
# **Ответ:** В VS Code в Source Control (раздел Merge Changes), внутри файла с конфликтными блоками, а также в GitHub Desktop при слиянии; команда git status показывает unmerged paths.
#
# ---
#
# ### Вопрос 23.1
#
# **Когда возникает конфликт?**
#
# **Ответ:** Когда Git не может автоматически совместить изменения двух версий — например, в одной и той же строке файла есть разные правки при merge, rebase или восстановлении stash.

# ### Вопрос 24
#
# **Как решить конфликт файлов?**
#
# **Ответ:** Открыть конфликтный файл, сравнить изменения, выбрать подходящий вариант или вручную объединить оба, удалить конфликтные маркеры, проверить итог, git add, затем завершить merge-коммитом или кнопкой Complete Merge.
#
# ---
#
# ### Вопрос 25
#
# **Какие изменения синие, а какие зелёные в показанном редакторе конфликтов?**
#
# **Ответ:** В примере из учебных ответов: зелёным обозначены пришедшие изменения (incoming), синим — текущие локальные (current). Цвета могут отличаться в других версиях или темах редактора; ориентироваться лучше по надписям Incoming и Current.
#
# ---
#
# ### Вопрос 26
#
