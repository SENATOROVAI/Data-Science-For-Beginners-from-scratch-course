# него.
#
# 6. Как понять, что ваш форк устарел?
#
# GitHub показывает, что ветка форка отстаёт от исходного репозитория,
# например This branch is 3 commits behind. Это означает, что в
# исходном репозитории появились коммиты, отсутствующие в форке.
#
# 6.1. Как обновить форк?
#
# Открыть свой fork и нажать Sync fork → Update branch. GitHub
# синхронизирует выбранную ветку с исходным репозиторием, если
# обновление не вызывает конфликтов.
#
# 7. Как добавить участников в репозиторий, чтобы команда могла
# работать над ним вместе?
#
# Открыть репозиторий → Settings → Collaborators (или Collaborators &
# teams) → Add people. Затем указать имя пользователя GitHub и
# отправить приглашение. После принятия приглашения пользователь
# получит доступ к репозиторию в соответствии с назначенными правами.
#
