# 9. Что такое файл README и зачем он нужен?
#
# README.md — файл с основной информацией о проекте. Обычно содержит
# описание проекта, инструкции по установке и запуску, примеры
# использования и другую полезную документацию. GitHub автоматически
# отображает его на главной странице репозитория.
#
# 9.1. Что такое файл CONTRIBUTING и зачем он нужен?
#
# CONTRIBUTING.md — файл с правилами участия в разработке проекта. В
# нём описывают порядок создания issues и pull requests, требования к
# оформлению кода, тестированию и сообщениям коммитов. Он помогает
# участникам соблюдать единые стандарты разработки.
#
# 10. Как изменить основную ветку?
#
# Открыть репозиторий → Settings → Default branch, выбрать другую
# ветку и подтвердить изменение. Для этого необходимы права
# администратора репозитория.
#
# 10.1. Как передать проект другому владельцу? Какая кнопка за это
# отвечает?
#
# Открыть репозиторий → Settings → General → Danger Zone → Transfer.
# Указать нового владельца и подтвердить передачу репозитория. Для
# передачи нужны административные права.
#
# 10.2. Что такое файл .gitignore?
#
# .gitignore — файл, содержащий правила исключения файлов и папок из
# отслеживания Git. Например, в него добавляют временные файлы, кеш,
# виртуальные окружения и локальные настройки.
#
# Файл .gitignore не удаляет файлы из репозитория и не прекращает
# отслеживание файлов, уже добавленных в Git.
