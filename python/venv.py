# 8. Что делают эти команды?
# pip install -r requirements.txt
# conda env create -f environment.yml
# 1) Устанавливает в текущее окружение все пакеты и их указанные версии из файла
# requirements.txt
# 2) Создает новое conda-окружение по описанию из файла environment.yml,
# откуда она берет имя,
# python нужной версии и все пакеты
#
# 9. Что делают эти команды?
# pip list
# pip show <название_пакета>
# conda list
# pip list выводит список пакетов в текущем окружении с их версиями.
# pip show <пакет> показывает подробную информацию об одном пакете: версию,
# описание,
# место установки и зависимости.
# conda list выводит список пакетов в активном conda-окружении
# (включая установленные через pip)
# с версиями, сборкой и каналом.
#
# venv или conda
#
# 10. Где по умолчанию больше пакетов — в venv/pip или в conda? Почему data scientists используют conda?
#
# По умолчанию больше пакетов в conda: дистрибутив Anaconda
# сразу содержит сотни библиотек
# для анализа данных, а новое venv-окружение почти пустое.
# Data scientists выбирают conda,
# потому что в ней уже есть нужные библиотеки,
# она умеет устанавливать не только библиотеки на Python,
# но и библиотеки на других языках, например на C++,
# и даёт выбрать версию Python для каждого окружения.
