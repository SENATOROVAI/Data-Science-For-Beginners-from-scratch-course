"""Список вопросов по работе с Issues на GitHub."""

# ## Общие вопросы
# Что такое Issues на GitHub и для чего они используются?
# - это встроенная в git cистема отслеживания задач, ошибок, предложений и обсуждения проекта - инструмент коммуникации с разработчиками проекта.
# используется для регистрации багов, предложений новых функций, постановки задач, вопросов и координации работы команды вокруг проекта.
#
# Чем Issues отличаются от других инструментов управления задачами?
# - Issues интегрированы с репозиториями: их можно связывать с PR, коммитами, ветками, назначить исполнителей, метки, этапы (Milestones) и проекты. Благодаря этому разработка и управление задачами ведутся в одном месте.
#
# Какие основные компоненты (поля) есть у каждого Issue?
# - Title; Description; Labels; Assignees; Milestone; Projects; Comments; State (Open/Closed)
#
# ## Создание Issues
# Как создать новое Issue в репозитории?
# - перейти в раздел issues проекта и нажать кнопку New Issue, выбрать шаблон, заполнить поля и нажать Create
#
# Какие данные рекомендуется указывать в описании Issue для лучшего понимания задачи?
# - Title с краткой сутью задачи и приложить ссылку на файл или конкретный фрагмент кода для уточнения исправления и Information с подробным описанием и логами ошибки, ссылки на связанный  PR, коммиты или Issues.
#
# Какие теги (labels) можно добавить к Issue? Какие из них стандартные?
# - практически любые, какие создадим. Стандартные: question, bug, documentation, duplicate, enhancement, help wanted, invalid, wontfix
# Как прикрепить Assignees (ответственных) к Issue?
# - в окне создания Issue нажать кнопку Assignee и выбрать исполнителей.
