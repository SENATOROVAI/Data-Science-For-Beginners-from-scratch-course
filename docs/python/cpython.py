# ## Введение в PyPy

# 14. Чем PyPy отличается от CPython?
#
# Cpython написан на языке C, PyPy написан на RPython (ограниченное подмножество Python)
# CPython Интерпретирует байт-код, PyPy - Трассирующий JIT: горячие циклы компилируются в машинный код
# PyPy Обычно в 3–10 раз быстрее, особенно в долгих циклах

# 15. Почему PyPy подходит не для всех проектов на Python?
#
# Проблемы с C-расширениями:
# - часть библиотек не устанавливается или работает с ошибками;
# - вызовы через слой совместимости cpyext (эмуляция C API CPython) медленные, и код на numpy/pandas под PyPy может работать медленнее, чем под CPython;
# - готовых сборок (wheels) под PyPy меньше, и пакеты часто приходится собирать из исходников.
# Отставание по версиям языка: PyPy поддерживает Python 3.10–3.11, а CPython уже 3.13–3.14.

# 16. Где можно скачать PyPy?
#
# На сайте https://pypy.org/

# ## Установка и запуск PyPy

# 17. Как установить PyPy после скачивания?
#
# Скачать ZIP-архив -> Распаковать архив -> Можно использовать pypy.exe

# 18. Как запустить файл с помощью PyPy?
#
# [Путь к файлу pypy.exe] [путь к файлу]
# Например: C:\pypy3.11\pypy.exe D:\hello.py

# 19. Почему PyPy выполняет код быстрее, чем CPython?
#
# CPython каждый раз интерпретирует общие инструкции, которые подходят для любых типов. PyPy наблюдает за реальным выполнением и компилирует горячие участки в машинный код, специализированный под реальные типы данных. Поэтому на долгих вычислениях на чистом Python он в разы быстрее.

