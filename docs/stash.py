"""[TASK] git stash."""

# 1. Что делает команда git stash?
#
# git stash временно сохраняет незакоммиченные изменения, убирая их из
# рабочей директории. По умолчанию новые неотслеживаемые файлы не
# сохраняются.
#
# 2. Как просмотреть список всех сохранённых изменений (стэшей)?
#
# git stash list показывает все сохранённые стэши.
#
# 3. Какая команда применяет верхний стэш?
#
# git stash apply применяет последний стэш, не удаляя его.
#
# 4. Как применить конкретный стэш по его номеру?
#
# git stash apply "stash@{2}" применяет стэш с номером 2.
#
# 5. Чем команда git stash apply отличается от git stash pop?
#
# apply оставляет стэш в списке, а pop удаляет его после успешного
# применения.
#
# 6. Что делает команда git stash drop?
#
# git stash drop удаляет один стэш, по умолчанию последний.
#
# 7. Как полностью очистить все сохранённые стэши?
#
# git stash clear очищает весь список стэшей.
#
# 8. В каких случаях удобно использовать git stash?
#
# Stash удобен, когда нужно временно переключиться на другую задачу,
# не создавая промежуточный коммит.
#
# 9. Что произойдёт, если выполнить git stash pop, когда в проекте
# есть конфликтующие изменения?
#
# При конфликте Git сообщит об ошибке. Конфликт нужно разрешить
# вручную, а стэш останется в списке.
#
# 10. Можно ли восстановить стэш, удалённый командой git stash drop?
#
# Иногда удалённый стэш можно восстановить через git fsck
# --unreachable, если соответствующие объекты ещё существуют. Гарантии
# нет.
#
# 11. Что делает команда git stash save "NAME_STASH"?
#
# git stash save "NAME_STASH" сохраняет изменения под указанным
# названием. Сейчас рекомендуется git stash push -m "NAME_STASH".
#
# 12. Что делает команда git stash apply <номер_стэша>?
#
# git stash apply "stash@{1}" восстанавливает выбранный стэш без его
# удаления.
#
# 13. Что делает команда git stash pop <номер_стэша>?
#
# Команда git stash pop <номер_стэша> применяет сохранённые изменения
# из указанного стэша к рабочей директории и, в случае успешного
# применения, удаляет этот стэш из списка. В отличие от git stash
# apply, который сохраняет стэш в списке.
