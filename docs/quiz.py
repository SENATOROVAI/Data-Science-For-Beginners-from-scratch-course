#
# **Ответ:** Да. Stash освобождает рабочую папку; затем можно сделать git pull. Нужно учитывать, что при возвращении stash возможен конфликт.
#
# ---
#
# ### Вопрос 26.1
#
# **Что может случиться после восстановления stash поверх pull?**
#
# **Ответ:** Если одни и те же строки изменились локально и удалённо, при git stash pop/apply появится конфликт. Его придётся разрешить вручную.
