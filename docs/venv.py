# pip show <название_пакета> - показывает версию, описание, автора, лицензию, расположение, от каких пакетов зависит и какие пакеты зависят от него
# conda list - показывает пакеты активного conda-окружения с версией, сборкой и каналом
#
# ## venv или conda
#
# 10. Где по умолчанию больше пакетов — в venv/pip или в conda? Почему data scientists используют conda?
# *Ответ:* conda. Она ставит не только Python-пакеты, но и нативные библиотеки. Пакеты приходят уже собранными, поэтому нет долгих сборок и проблем с компиляторами. Сама conda ставит нужную версию Python под каждый проект
