# conda env create -f environment.yml - устанавливает пакеты и зависимости из файла environment.yml
# 9. Что делают эти команды?
# pip list — показывает список установленных Python-пакетов.
# pip show <название_пакета> — выводит подробную информацию о конкретном пакете
# conda list — показывает список установленных пакетов
# venv или conda. venv — это встроенный в Python инструмент для создания изолированных виртуальных окружений.  conda - система управления пакетами и виртуальными окружениями.
# 10. Где по умолчанию больше пакетов — в venv/pip или в conda? Почему data scientists используют conda?
# в pip больше пакетов, потому что он для всех пользователей python. В conda их меньше, потому что он для data scientists, именно поэтому они его и используют.
