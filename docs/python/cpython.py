# 18. Почему PyPy выполняет код быстрее, чем CPython?<br>
# *Ответ:* Потому что JIT-компилятор PyPy во время работы выявляет «горячие»
# участки кода (часто выполняемые циклы и функции), оптимизирует их с учётом
# реальных типов данных и компилирует в машинный код. Поэтому такие участки
# выполняются быстрее, чем при интерпретации байт-кода в CPython. Ускорение не
# постоянно: оно зависит от характера задачи.
