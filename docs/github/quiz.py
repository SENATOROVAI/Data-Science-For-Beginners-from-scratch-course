# ## 3. Рабочий процесс с использованием GitHub
#
# **3. 8 шагов, чтобы внести вклад в чужой проект**
#
# 1. Сделать fork проекта.
# 2. Создать тематическую ветку от основной ветки (`main` / `master`).
# 3. Сделать коммиты с улучшениями.
# 4. Отправить ветку в свой форк на GitHub (`git push`).
# 5. Открыть pull request в исходный проект.
# 6. Обсудить изменения и при необходимости добавить новые коммиты.
# 7. Владелец проекта сливает (merge) или закрывает pull request.
# 8. Синхронизировать свой форк с обновлённой основной веткой исходного проекта.
#
# **3.1. Какие практики принято соблюдать, чтобы issue закрывался автоматически?**
#
# - **При создании pull request** — в описании PR написать ключевое слово и номер или ссылку на issue: `Closes #123`, `Fixes #123` или `Resolves #123`. Issue закроется, когда PR сольют в основную ветку.
# - **При создании коммита** — то же ключевое слово указать в описании (теле) коммита, а не в заголовке: `Closes #123`. Issue закроется, когда коммит попадёт в основную ветку.
#
# Заголовок коммита и PR пишут по Conventional Commits без номера issue. Если работа сделана частично, пишут `Refs #123`: ссылка появится, но issue останется открытым.
#
# **3.2. Как отклонить или закрыть pull request?**
#
# Открыть pull request на вкладке **Conversation**, прокрутить вниз до поля комментария и нажать кнопку **Close pull request**. Можно сначала написать комментарий с причиной: тогда кнопка называется **Close with comment**. Закрытый PR можно снова открыть кнопкой **Reopen pull request**.
#
# ![Кнопка Close pull request внизу вкладки Conversation](attachment:close-pr.png)
#
# **3.3. Нужно ли создавать issue перед отправкой pull request?**
#
# Не обязательно: pull request можно открыть и без issue, по сути это issue с прикреплённым кодом. Но для заметных изменений лучше сначала создать issue и обсудить идею с мейнтейнерами, чтобы не делать работу, которую не примут. Многие проекты требуют это в CONTRIBUTING, и тогда PR привязывают к issue ключевым словом.
#
# **3.4. На какой вкладке можно посмотреть список изменений в pull request? (Рисунок 92)**
#
# На вкладке **Files changed**.
#
# **3.5. На какой вкладке находится страница обсуждения pull request? (Рисунок 94)**
#
# На вкладке **Conversation**.

# ## 4. Создание pull request
#
# **4. Можно ли открыть pull request, если вы ничего не изменили в форке?**
#
# Нет. Pull request показывает разницу между ветками, и если её нет, GitHub пишет, что сравнивать нечего, и кнопки создания PR не будет. Нужен хотя бы один коммит, которого нет в целевой ветке.
#
# **4.1. Что нужно сделать, чтобы открыть pull request? (Рисунок 90)**
#
# Отправить ветку с коммитами в свой форк и открыть его на GitHub. Появится подсказка о недавно отправленной ветке с кнопкой **Compare & pull request**; другой путь — вкладка **Pull requests** → **New pull request**. Затем выбрать base (куда) и compare (откуда), заполнить заголовок и описание и нажать **Create pull request**.
#
# **4.2. Что делать, если ваш форк устарел?**
#
# Обновить его из исходного репозитория: нажать **Sync fork** → **Update branch** на странице форка или сделать это локально через remote `upstream` (см. 6.1). Если это мешает открытому PR, нужно влить свежую основную ветку оригинала в свою ветку и отправить её: PR обновится сам.
#
# **4.3. Что делать, если в pull request есть конфликты слияния? (Рисунок 96)**
#
# Если GitHub пишет, что PR нельзя слить автоматически, конфликты решают в своей ветке:
#
# ```bash
# git remote add upstream https://github.com/<владелец>/<репозиторий>.git
# git fetch upstream
# git merge upstream/main
# # исправить конфликтующие файлы
# git add .
# git commit
# git push origin <ветка>
# ```
#
# Вместо `merge` можно сделать `rebase` на свежую основную ветку. После `push` PR обновится и станет доступен для слияния. Простые конфликты можно решить и в браузере кнопкой **Resolve conflicts**.

