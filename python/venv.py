# Создание и активация окружения
# 1. Что делает команда python -m venv venv?
# Эта команда создаст виртуальное окружение с названием venv
#
# 2. Что делает каждая команда в списке ниже?
# ![task2](images/task2.jpg)
# 1) перечисляет какие пакеты есть в данном окружении и их версии
# 2) пакеты записываются вместе с точными версиями в файл под названием
#  requirements.txt
# 3) данная команда нужна если вы хотите загрузить одной командой все
#  зависимости из файла под названием requirements.txt
#
# 3. Что делает каждая команда в списке ниже?
# ![task3](images/task3.jpg)
# 1) перечисляет какие есть conda-окружения
# 2) создает окружение с именем env_name, устанавливая туда Python с версией
# 3.5
# 3) обновляет окружение env_name, устанавливая пакеты или обновляя их по
# списку
# их file.yml
# 4) активирует окружение env_name
# 5) деактивирует окружение
# 6) очищает кэш conda: неиспользуемые пакеты, кэш индексов, скачанные архивы
#
