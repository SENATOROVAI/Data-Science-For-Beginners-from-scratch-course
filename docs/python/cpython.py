# 1. Что такое CPython и чем он отличается от Python?
# - CPython - это наиболее распространенная реализация Python с компилятором, написанная на С и компилируется С-компилятором.
# - CPython используется для выполнения большинства Python-программ.
# - Это не ЯП это реализация Python на языке программирования C.
# - Реализация исполняет байт-код, созданный интерпретатором.
# - Python описывет синтаксис, а CPython интерпретирует их.
#
# 2. Официально порядка 9, но в лекции упоминается 6.
#
# 4. На С.
#
# 5. Guido van Rossum
#
# 6. Python считается языком с высокой скоростью разработки, он уступает по скорости исполнения с С или Rust, но многие тяжелые вычисления выполняются не на Python, а на высокопроизводительных библиотеках, написанных на С и С++ или Fortran.
#
# Он быстр за счет компиляции в байт-код, а не разбирается построчно, а также имеет быстрый интерпретатор CPython и оптимизированные библиотеки NumPy6, Pandas, OpenCV, TensorFlow выполняет тяжелые операции на С/C++ которая выполняется на CPU.
#
# Но Python медленнее С, поскольку каждая операция работает с полноценным объектом, а не байт-кодом, но для реализации ПО требуется меньше кода.
