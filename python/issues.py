"""Ответы по Issues."""

# pylint: disable=invalid-name


# 1. Что такое Issues на GitHub и для чего они используются?
# встроенный трекер задач GitHub. В нём ведут баги, идеи,
# вопросы и обычные задачи по проекту

# 2. Чем Issues отличаются от других инструментов управления задачами?
#  Issues встроены прямо в репозиторий и связаны с кодом: Issue можно
# привязать к коммиту или PR

# 3. Какие основные компоненты (поля) есть у каждого Issue?
# описание,статус,тип,комментарии

# 4. Как создать новое Issue в репозитории?
# вкладка issues  new issues заголовок и submit

# 5. Какие данные рекомендуется указывать в описании Issue для лучшего №понимания задачи?
# четкое описание проблемы, ожидаемый результат, возможные метрики,
# информация или скрины

# 6. Какие теги (labels) можно добавить к Issue? Какие из них стандартные?
# Стандартные: bug, documentation, duplicate, enhancement, good first issue, help wanted, invalid, question, wontfix. Свои метки можно создавать с любым названием и цветом.


# 7. Как прикрепить Assignees (ответственных) к Issue?
#  кнопка Assignees

# 8. Как использовать Labels для классификации задач?
# Метками помечают тип (bug, feature), приоритет (high, low), область (docs, №frontend) или статус. Потом по ним фильтруют список. Управлять метками можно №в Issues → Labels.

# 9. Для чего нужен Milestone, и как связать его с Issue?
# Milestone объединяет Issues и PR и показывает прогресс выполнения в
# процентах. Чтобы связать его с Issue, в правой панели Issue выберите
# Milestone

# 10. Как привязать Issue к пул-реквесту (Pull Request)?
# Написать в описании PR Closes номер или полную ссылку на Issue. В правой №панели PR выбрать Development и добавить Issue. Либо в Issue нажать Development


# 11. Как добавить комментарий к существующему Issue?
# открыть его и внизу будут поле для коммента

# 12. Как закрыть Issue вручную?
# Внизу Issue нажать Close issue

# 13.Можно ли автоматически закрыть Issue с помощью сообщения в коммите или №пул-реквесте? Как это сделать?
# Да. В описании PR или в сообщении коммита пишут ключевое слово (close,
# closes, fix, fixes, resolve, resolves), затем номер Issue, например
# Closes 42; Issue закроется при слиянии в основную ветку.
# 14. Как повторно открыть закрытое Issue, если работа ещё не завершена?
# кнопка reopen

# 15. Как найти все открытые или закрытые Issues в репозитории?
# есть фильтр по нему и искать написать is:open или is:closed.


# 16. Как использовать фильтры для поиска Issues по меткам, исполнителям или №другим критериям?
# Фильтры сверху (Author, Label, Milestone, Assignee и др.) или запрос в №строке поиска, например is:issue is:open label:bug assignee:username. Есть и №no:assignee для задач без исполнителя.

# 17. Как сортировать Issues по приоритету, дате создания или другим №параметрам?
# Меню Sort: Newest, Oldest, Most commented, Least commented, Recently updated №и другие. Отдельного поля «приоритет» в обычном списке нет. Его заменяют №метками либо полем Priority в Projects.

# 18. Как настроить автоматические уведомления о новых или изменённых Issues?
# # нажать Subscribe и в настройках Settings → Notifications выбрать тип
# уведомлений


# 19. Что такое Projects в контексте GitHub, и как связать их с Issues?
# Projects  доска   для планирования и отслеживания работы. Issues и PR №добавляются туда как карточки с полями

# 20. Какие сторонние инструменты можно использовать для автоматизации работы №с Issues (например, боты, Webhooks)?
# GitHub Actions,GitHub Apps,GitHub CLI

# 21. Как упомянуть другого пользователя в комментарии к Issue?
# через собачку @

# 22. Как запросить дополнительные данные или уточнения у автора Issue?
# Оставить комментарий автору и конкретными вопросами

# 23. Что делать, если Issue неактуально или его нужно объединить с другим?
# закрыть как «not planned» с объяснением причины.
#

# 24. Как использовать шаблоны для создания Issues?
# # Создать в репозитории папку .github/ISSUE_TEMPLATE/ и положить туда
# файлы шаблонов


# 25. Что такое Linked Issues, и как создать связь между задачами?
# Это связанные между собой задачи и PR.

# 26. Какие метрики (например, время выполнения) можно отслеживать с помощью #Issues?
# Время от открытия до закрытия, число открытых и закрытых Issues, возраст #задач, активность в комментариях,


# 27. Какие best practices рекомендуются при работе с Issues в команде?
# Понятные заголовки и описания, один Issue — одна задача. Шаблоны, метки, #Milestones и назначенные исполнители. Связывать Issues с PR и закрывать их #через Closes #N. Регулярно разбирать список и закрывать устаревшее.
