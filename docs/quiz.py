# 15. Что такое «Go To» и чем это полезно? Как сразу перейти к ячейке с ошибкой?
#
# «Go To» — группа команд VS Code для быстрого перехода: к строке, файлу, функции или заголовку, без прокрутки мышью. Полезно в больших файлах и ноутбуках (у меня 88 ячеек).
#
# Основные варианты:
# - Ctrl+G -> перейти к строке по номеру.
# - Ctrl+P -> перейти к файлу по имени.
# - Ctrl+Shift+O -> перейти к функции, переменной или заголовку Markdown-ячейки в текущем файле или ноутбуке.
#
# Как перейти к ячейке с ошибкой:
# - В выводе ячейки с ошибкой в трассировке написано «Cell In[N], line M». Это ссылка: Ctrl+клик по ней -> откроется нужная ячейка и строка.
# - Если ячеек много, открыть Outline (структура ноутбука) на боковой панели или нажать на «Cell X of Y» внизу в строке состояния, затем выбрать нужную ячейку.

