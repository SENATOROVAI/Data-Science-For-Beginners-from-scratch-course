# 22. Что такое stash? Объясните концепцию в общих чертах.
#
#     *Ответ:* stash это временное локальное хранилище Git для незакоммиченных изменений.
#
#     22.1. Как сохранить изменения в stash?
#         - git-команда: git stash push -m "NAME_STASH"
#         - кнопка в VS Code: Source Control > меню … > Stash.
#
#     22.2. Как восстановить stash (подсказка)?
#     *Ответ:* в кошке stash changes > restore
#
#         git-команда (подсказка): git stash apply "NUMBER_STASH"
#
#     22.3. Чем stash отличается от коммита? Когда лучше сохранить изменения в stash, а когда — закоммитить?
#     *Ответ:* коммит это постоянная точка в истории ветки: он отправляется на гитхаб и доступен всем. Stash это временное локальное хранилище: в историю ветки он не попадает, на гитхаб не уходит, привязан к вашему компьютеру и хранится недолго
#     В stash лучше прятать незаконченную работу, когда нужно ненадолго отвлечься
#     Коммитить лучше готовый, логически завершённый результат.
#
#     22.4. Как просмотреть список сохранённых stash?
#     *Ответ:* В VS Code: Source Control > … > Stash. в кошке можно посмотьреть Changes > пункт Stashed Changes
#         - git-команда (подсказка): git stash list
#
#     22.5. Как удалить stash? Приведите команды для удаления отдельной записи и всех сразу.
#     *Ответ:*
#         git-команда (подсказка):
#         - git stash clear – очистить все сразу;
#         - git stash drop - удаляется последняя запись, либо нужно указать явно git stash drop stash@{n}
#         - git stash pop - добавляет стэш и удаляет, либо git stash pop stash@{n}
#
#     22.6. Приведите практические примеры использования stash — краткие сценарии, где он помогает.
# *Ответ:*
#     - нужно срочно переключиться в другую ветку, не коммитя недоделанную работу
#     - нужно ненадолго отложить работу (например, перейти к другой задаче) и не оставлять в истории «сырой» коммит
#     - нужно принять пул, а в рабочей папке есть незакоммиченные правки
#     - когда нужно переключиться на другой репозиторий не завершая работу с текущим
#     - начали работать не в той ветке: спрятать правки, переключиться на нужную ветку и вернуть их там.
