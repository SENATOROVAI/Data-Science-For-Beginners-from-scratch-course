"""Решение квиза по github issues."""

#
# ОБЩИЕ ВОПРОСЫ
#
# 1. Что такое Issues на GitHub и для чего они используются?
# Issues — задачи для отслеживания ошибок, улучшений и новых функций.
#
# 2. Чем Issues отличаются от других инструментов управления задачами?
# Они встроены в GitHub и напрямую связаны с кодом, коммитами и PR.
#
# 3. Какие основные компоненты есть у каждого Issue?
# Название, описание, статус, автор, исполнители, метки, Milestone и
# комментарии.
#
# СОЗДАНИЕ ISSUES
#
# 4. Как создать новое Issue?
# Открыть репозиторий → Issues → New issue → заполнить поля → Create.
#
# 5. Какие данные указывать в описании?
# Суть задачи, ожидаемый результат, шаги воспроизведения ошибки и скриншоты
# при необходимости.
#
# 6. Какие Labels можно добавить? Какие стандартные?
# Стандартные: bug, documentation, enhancement, duplicate, good first issue,
# help wanted, invalid, question, wontfix. Можно создавать свои.
#
# 7. Как назначить Assignees?
# Открыть Issue и выбрать исполнителя в поле Assignees.
#
# РАБОТА С ISSUES
#
# 8. Как использовать Labels?
# Для классификации задач по типу, приоритету или области работы.
#
# 9. Для чего нужен Milestone?
# Для объединения задач в этап проекта, например Release 1.0. Назначается
# через поле Milestone.
#
# 10. Как привязать Issue к Pull Request?
# Указать в описании PR, например Closes #15.
#
# 11. Как добавить комментарий?
# Открыть Issue, написать текст в поле комментария и нажать Comment.
#
# ЗАКРЫТИЕ ISSUES
#
# 12. Как закрыть Issue вручную?
# Открыть задачу и нажать Close issue.
#
# 13. Как закрыть Issue автоматически?
# Использовать Closes #15, Fixes #15 или Resolves #15 в PR или коммите.
# Закрытие произойдёт при попадании изменений в основную ветку.
#
# 14. Как повторно открыть Issue?
# Открыть закрытую задачу и нажать Reopen issue.
#
# ФИЛЬТРАЦИЯ И ПОИСК
#
# 15. Как найти открытые или закрытые Issues?
# Во вкладке Issues выбрать Open или Closed.
#
# 16. Как использовать фильтры?
# Например:
# is:open — открытые
# label:bug — ошибки
# assignee:Boltorn — задачи исполнителя
# author:Boltorn — задачи автора
#
# 17. Как сортировать Issues?
# Через Sort по дате, обновлениям, комментариям. По приоритету —
# через Projects или метки.
#
# ИНТЕГРАЦИИ И АВТОМАТИЗАЦИЯ
#
# 18. Как настроить уведомления?
# Через Watch → Custom → Issues или Subscribe для отдельной задачи.
#
# 19. Что такое GitHub Projects?
# Инструмент управления задачами в виде доски или таблицы. Issue
# добавляется через поле Projects.
#
# 20. Какие инструменты автоматизации существуют?
# GitHub Actions, Webhooks, Probot, Dependabot, Jira, Slack.
#
# СОВМЕСТНАЯ РАБОТА
#
# 21. Как упомянуть пользователя?
# Написать @username в комментарии.
#
# 22. Как запросить уточнения?
# Оставить комментарий с вопросом и упомянуть автора через @.
#
# 23. Что делать с неактуальным или повторяющимся Issue?
# Закрыть как Not planned или Duplicate, указав оригинальную задачу.
#
# ПРАКТИЧЕСКИЕ АСПЕКТЫ
#
# 24. Как использовать шаблоны Issues?
# Создать шаблоны в .github/ISSUE_TEMPLATE/. При создании задачи
# выбрать нужный.
#
# 25. Что такое Linked Issues?
# Связанные задачи. Их можно связать через #номер, Sub-issues или
# зависимости Blocking / Blocked by.
#
# 26. Какие метрики можно отслеживать?
# Количество задач, время до закрытия, число ошибок, прогресс Milestone
# и активность исполнителей.
#
# 27. Какие best practices рекомендуются?
# Понятные названия, подробные описания, Labels, Assignees, шаблоны,
# небольшие задачи и своевременное закрытие Issues.
#
