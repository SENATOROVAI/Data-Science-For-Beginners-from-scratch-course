# ## Общая информация
#
# **1. Есть ли у проекта лицензия?**
#
# Да: в корне репозитория лежит файл [`LICENSE`](https://github.com/Kaggle/kagglehub/blob/main/LICENSE), лицензия **Apache-2.0**.
#
# **2. Название компании и ссылка на репозиторий**
#
# Kaggle (входит в Google): https://github.com/Kaggle/kagglehub
#
# `kagglehub` — Python-библиотека для скачивания и загрузки моделей, датасетов, ноутбуков и соревнований Kaggle.
#
# **3. Принимает ли проект стороннюю помощь?**
#
# Да. В [`CONTRIBUTING.md`](https://github.com/Kaggle/kagglehub/blob/main/CONTRIBUTING.md) приглашают открывать issue и pull request, а мелкие исправления разрешают присылать сразу, без обсуждения. Внешние PR действительно сливают, например [#307](https://github.com/Kaggle/kagglehub/pull/307), [#306](https://github.com/Kaggle/kagglehub/pull/306), [#298](https://github.com/Kaggle/kagglehub/pull/298) и [#292](https://github.com/Kaggle/kagglehub/pull/292) (исправление опечатки в README). Чтобы PR можно было слить, автор должен подписать Google CLA (проверка `cla/google`).
#
# **4. Какое второе улучшение вы сделали?**
#
# Исправил опечатки в документации, их нашёл `codespell`: в README (слова adapter, Prerequisites, overridden), в тексте предупреждения в `kaggle_cache_resolver.py` (access, of), в docstring в `models.py` (transparent) и в справке скрипта `docker-hatch` (specific): https://github.com/Kaggle/kagglehub/pull/326
#
# Первое улучшение — исправление PEP8 (E501, строки длиннее 120 символов): https://github.com/Kaggle/kagglehub/pull/325 по issue [PEP8 WIP](https://github.com/Kaggle/kagglehub/issues/324).

