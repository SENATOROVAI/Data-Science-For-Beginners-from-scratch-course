# **22.** Что такое валидация?

# **Ответ:** Валидация — это подтверждение того, что код прошёл проверки


# **23.** Что такое трассировка (traceback) ошибки?

# **Ответ:** Трассировка (traceback) — подробный отчёт Python об ошибке: цепочка вызовов с номерами ячеек и строк, где возникла ошибка, а в последней строке — тип ошибки и её описание. По ней находят место, где код упал.

# **24.** Что значит «отвалился интерпретатор»?

# **Ответ:** Значит, что процесс интерпретатора (ядро ноутбука) аварийно завершился или перестал отвечать: ячейки перестают выполняться. Обычно помогает перезапуск ядра (Restart).
