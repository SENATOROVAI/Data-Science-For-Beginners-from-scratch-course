# ## 9. Особые файлы
#
# **9. Что такое файл README и зачем он нужен?**
#
# README (`README.md`, `README.rst`, `README`) — главный файл описания проекта, GitHub показывает его на главной странице репозитория. В нём обычно пишут, для чего проект, как его установить и использовать, какие у него зависимости, лицензия и как связаться с авторами или помочь проекту.
#
# **9.1. Что такое файл CONTRIBUTING и зачем он нужен? (Рисунок 122)**
#
# `CONTRIBUTING` (`CONTRIBUTING.md`) — правила для тех, кто хочет внести вклад: как оформлять issue и pull request, стиль кода и коммитов, как запускать тесты, нужно ли подписывать CLA. При создании PR или issue GitHub показывает ссылку на этот файл, чтобы участник прочитал правила до отправки.

# ## 10. Управление проектом
#
# **10. Как изменить основную ветку? (Рисунок 123)**
#
# **Settings** → **General** → раздел **Default branch** → кнопка переключения ветки (⇄) → выбрать ветку → **Update** и подтвердить. Новая ветка станет базовой для новых pull request и будет открываться по умолчанию при просмотре и клонировании репозитория.
#
# **10.1. Как передать проект другому владельцу? Какая кнопка за это отвечает? (Рисунок 124)**
#
# **Settings** → **General** → внизу раздел **Danger Zone** → **Transfer ownership**, кнопка **Transfer**. Нужно указать нового владельца (пользователя или организацию) и подтвердить именем репозитория. GitHub перенесёт репозиторий со всеми issues, PR и звёздами и настроит перенаправление со старого адреса.
#
# **10.2. Что такое файл `.gitignore`?**
#
# `.gitignore` — файл с шаблонами путей, которые Git не должен отслеживать: виртуальные окружения (`.venv/`), кэш (`__pycache__/`), файлы с секретами (`.env`), логи и результаты сборки. Шаблоны действуют только на ещё не отслеживаемые файлы: уже закоммиченный файл нужно сначала убрать из индекса командой `git rm --cached`.
