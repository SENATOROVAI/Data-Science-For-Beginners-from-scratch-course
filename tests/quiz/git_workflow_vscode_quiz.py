# Пакетный менеджер — программа, которая устанавливает, обновляет и удаляет библиотеки и следит за их зависимостями.
#
# - **pip** — стандартный менеджер Python, ставит пакеты из PyPI.
# - **conda** — менеджер пакетов и окружений из Anaconda/Miniconda; умеет ставить и не-Python зависимости (C-библиотеки, CUDA).
#
# Я пользуюсь pip вместе с виртуальными окружениями (`venv`). В data science часто выбирают conda, потому что она проще ставит тяжёлые научные библиотеки; но сейчас почти всё есть в виде готовых wheel для pip, поэтому оба варианта рабочие. Главное — не смешивать их бездумно в одном окружении.

# **3. Почему расширение .py лучше, чем .ipynb?**

# - `.py` — обычный текст: diff в Git читается легко, конфликты разрешать проще;
# - линтеры, форматеры и тесты работают с `.py` напрямую;
# - код можно импортировать как модуль и запускать из терминала;
# - в `.py` нет выводов ячеек и метаданных, файл меньше и чище.
#
# `.ipynb` удобен для исследований и визуализации, но для production-кода и code review лучше `.py`.

# **4. Что такое PEP 8? (подсказка)**

# PEP 8 — официальное руководство по стилю кода на Python (https://peps.python.org/pep-0008/): отступы в 4 пробела, длина строк, пробелы вокруг операторов, именование, порядок импортов, пустые строки и т.д. Цель — единообразный и читаемый код.

# **4.1. Проверяют ли линтеры соблюдение PEP 8?**

# Да. Например, pycodestyle/flake8 и Ruff (правила `E`, `W`, `N`), pylint; а black и `ruff format` автоматически форматируют код в стиле, совместимом с PEP 8.

# **4.2. Какая нотация используется для именования переменных? (ответ на стр. 85–95: https://t.me/c/1937296927/1/16676)**

# **snake_case** — слова в нижнем регистре через подчёркивание: `user_name`, `total_sum`. Для классов — `CamelCase` (`DataLoader`), для констант — `UPPER_CASE` (`MAX_SIZE`).

# **4.3. Может ли имя переменной состоять из одного символа, например из подчёркивания _?**

# Да, синтаксически это допустимое имя: `_ = 5` работает. Но в курсе однобуквенные имена запрещены линтером (flake8-variables-names, правило VNE001), поэтому лучше давать понятные имена.

# **4.4. Зачем и где используется подчёркивание _?**

# - Переменная-«заглушка», значение которой не нужно: `for _ in range(3):`, `name, _ = pair`.
# - В интерактивном интерпретаторе `_` хранит результат последнего выражения.
# - `_name` — «внутреннее» (приватное по соглашению) имя.
# - `__name` — изменение имени (name mangling) в классах.
# - `__init__`, `__str__` — специальные (dunder) методы.
# - `class_`, `type_` — чтобы не конфликтовать с ключевыми словами и встроенными именами.
# - Разделитель разрядов: `1_000_000`.
# - Шаблон «что угодно» в `match/case`: `case _:`.

# **4.5. Допустимо ли по PEP 8 имя переменной из одной буквы? (ответ на стр. 85–95: https://t.me/c/1937296927/1/16676)**

# PEP 8 прямо не запрещает однобуквенные имена, но требует никогда не использовать `l`, `O` и `I` — их легко спутать с цифрами 1 и 0. Однобуквенные имена допустимы разве что для коротких счётчиков, но хорошей практикой считаются осмысленные имена. В конфигурации линтеров курса однобуквенные имена переменных запрещены.

