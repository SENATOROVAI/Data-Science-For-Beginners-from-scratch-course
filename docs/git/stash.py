"""What is stash."""

# Что делает команда git stash?
# - временно сохраняет все незакоммиченные изменения в специальное локальное
#   хранилище Git (stash) и восстанавливает состояние последнего коммита.
#
# Как просмотреть список всех сохранённых изменений (стэшей)?
# - git stash list
#
# Какая команда применяется для использования верхнего стэша?
# - git stash pop, если нужно оставить стэш в истории, то git stash apply
#
# Как применить конкретный стэш по его номеру?
# - git stash pop stash@{1}
#
# Чем отличается команда git stash apply от git stash pop?
# - git stash apply применяет изменения, но не удаляет стэш
#   git stash pop - применяет изменения и удаляет стэш из списка при
#   успешном применении.
#
# Что делает команда git stash drop?
# - удаляет указанный стэш
#
# Как полностью очистить все сохранённые стэши?
# - git stash clear
#
# В каких случаях удобно использовать git stash?
# - для временного сохранения нужных незакоммиченных изменений для:
# -- переключения на другую ветку
# -- выполнения git pull
# -- срочно исправить другую задачу
# -- протестировать другую версию проекта
# -- освободить рабочую директорию без создания коммита
#
# Что произойдёт, если выполнить git stash pop, но в проекте есть
# конфликтующие изменения?
# - Git попытается применить изменения. При конфликте Git сообщит о нём,
#   конфликт нужно разрешить вручную. В этом случае стэш не удаляется
#   автоматически.
#
# Можно ли восстановить удалённый стэш после выполнения git stash drop?
# - Запись о стэше удаляется из списка и обычно не видна в git reflog.
#   Восстановить его можно по хэшу коммита, который git stash drop выводит
#   в терминал: git stash apply <хэш>. Если хэш потерян, можно найти
#   потерянные коммиты через git fsck --unreachable, пока их не удалил
#   сборщик мусора (git gc). Гарантий нет.
#
# Что делает команда git stash save "NAME_STASH"
# - сохраняет изменения в новый стэш с указанным описанием, но сейчас
#   используется новая команда git stash push -m "NAME_STASH"
#
# Что делает команда git stash apply "NUMBER_STASH"
# - применяет указанный стэш, не удаляя его из истории:
#   git stash apply stash@{N}
#
# Что делает команда git stash pop "NUMBER_STASH"
# - применяет выбранный стэш и удаляет его из истории
#
# Сохраните текущие изменения в стэш под названием "SENATOROV ver1",
# вставьте вывод из терминала
# - git stash push -m "SENATOROV ver1"
#   Saved working directory and index state On main: SENATOROV ver1
#
# Внесите любые изменения в ваш репозиторий и сохраните второй стэш под
# именем "SENATOROV ver2"
# - git stash push -m "SENATOROV ver2"
#   Saved working directory and index state On main: SENATOROV ver2
#
# Восстановите ваш стэш "SENATOROV ver1", вставьте вывод из терминала
# - git stash list
#   stash@{0}: On main: SENATOROV ver2
#   stash@{1}: On main: SENATOROV ver1
# - git stash apply stash@{1}
#
# Удалите все стэши из истории, вставьте вывод из терминала
# - git stash clear
# - git stash list
#   (пустой вывод)
