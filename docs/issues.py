"""[TASK] github issues."""

# 1. Что такое Issues на GitHub и для чего они используются?
#
# Issues — это задачи внутри репозитория GitHub. В них фиксируют
# ошибки, идеи, улучшения и другую работу, которую нужно обсудить или
# выполнить.
#
# 2. Чем Issues отличаются от других инструментов управления задачами?
#
# Главное отличие — тесная связь с репозиторием: Issue можно связать с
# коммитом, веткой и Pull Request. Для работы над кодом это удобно,
# хотя для сложного планирования Jira и другие системы могут
# предлагать больше настроек.
#
# 3. Какие основные компоненты (поля) есть у каждого Issue?
#
# У каждого Issue есть номер, заголовок, автор, статус и даты создания
# и обновления. Описание и комментарии могут отсутствовать.
# Дополнительно можно указать исполнителей, метки, milestone, проект и
# связи с другими задачами.
#
# 4. Как создать новое Issue в репозитории?
#
# Открыть репозиторий, перейти в Issues → New issue, выбрать шаблон
# при необходимости, заполнить заголовок и описание и нажать Submit
# new issue. В репозитории должна быть включена поддержка Issues.
#
# 5. Какие данные рекомендуется указывать в описании Issue, чтобы
# задача была понятна?
#
# Нужно объяснить, что произошло или что требуется сделать, и указать
# ожидаемый результат. Для ошибки полезны шаги воспроизведения,
# фактический результат, версия программы и логи или скриншоты.
# Секретные данные публиковать нельзя.
#
# 6. Какие метки (Labels) можно добавить к Issue? Какие из них
# стандартные?
#
# Часто используют стандартные метки bug, documentation, duplicate,
# enhancement, good first issue, help wanted, invalid, question и
# wontfix; в новых репозиториях также может быть accessibility. Свои
# метки, например priority:high или backend, можно создать отдельно.
#
# 7. Как назначить ответственных (Assignees) за Issue?
#
# Открыть Issue, справа нажать Assignees и выбрать пользователя из
# доступного списка. Назначать исполнителей можно при наличии
# необходимых прав в репозитории.
#
# 8. Как использовать Labels для классификации задач?
#
# Метки помогают разделять задачи по типу, компоненту или срочности,
# например bug, frontend или priority:high. Одному Issue можно
# назначить несколько меток, а затем фильтровать задачи по ним.
#
# 9. Для чего нужен Milestone и как связать его с Issue?
#
# Milestone объединяет задачи общей целью, например выпуском версии, и
# позволяет отслеживать их выполнение. Его создают в Issues →
# Milestones, а затем выбирают в поле Milestone нужного Issue.
#
# 10. Как привязать Issue к пул реквесту (Pull Request)?
#
# Можно написать в описании PR Closes #15 или связать его с задачей
# через раздел Development. При слиянии PR в основную ветку связанное
# Issue закроется автоматически.
#
# 11. Как добавить комментарий к существующему Issue?
#
# Открыть нужное Issue, написать сообщение в поле комментария внизу
# страницы и нажать Comment.
#
# 12. Как закрыть Issue вручную?
#
# Открыть Issue и нажать Close issue. При необходимости можно выбрать
# причину закрытия, например Completed или Not planned.
#
# 13. Можно ли закрыть Issue автоматически с помощью сообщения в
# коммите или пул реквесте? Как это сделать?
#
# Да. Например, указать Fixes #12 или Closes #12 в описании PR либо в
# сообщении коммита. GitHub закроет Issue, когда соответствующие
# изменения попадут в основную ветку репозитория.
#
# 14. Как повторно открыть закрытое Issue, если работа ещё не
# завершена?
#
# Открыть закрытое Issue и нажать Reopen issue, если у пользователя
# есть право его повторно открыть.
#
# 15. Как найти все открытые или закрытые Issues в репозитории?
#
# На вкладке Issues выбрать Open или Closed. Также можно искать через
# запросы is:issue is:open и is:issue is:closed.
#
# 16. Как использовать фильтры для поиска Issues по меткам,
# исполнителям и другим критериям?
#
# Использовать строку поиска или меню фильтров. Например, is:issue
# is:open label:bug assignee:USERNAME покажет открытые ошибки,
# назначенные выбранному пользователю. Также доступны фильтры по
# автору, milestone и другим полям.
#
# 17. Как сортировать Issues по приоритету, дате создания и другим
# параметрам?
#
# Через меню Sort можно выбрать дату создания, последнего обновления,
# число комментариев и другие варианты. Для приоритета удобнее задать
# поле Priority в Projects или использовать специальные метки: в
# обычном списке Issues сортировки по приоритету по умолчанию нет.
#
# 18. Как настроить уведомления о новых или изменённых Issues?
#
# В репозитории открыть Watch → Custom и включить уведомления для
# Issues. На отдельное Issue можно подписаться через Subscribe. Способ
# доставки уведомлений настраивается в настройках GitHub.
#
# 19. Что такое Projects на GitHub и как связать их с Issues?
#
# Projects — инструмент планирования задач в виде таблицы, доски или
# дорожной карты. Чтобы добавить Issue, можно выбрать нужный проект в
# поле Projects на странице задачи и затем настроить статус или
# приоритет.
#
# 20. Какие сторонние инструменты можно использовать для автоматизации
# работы с Issues (например, боты, Webhooks)?
#
# Можно использовать ботов на Probot, интеграции с Jira, Slack или
# Zapier и собственные обработчики Webhooks. Например, Webhook может
# отправлять уведомление при создании Issue. Внутри GitHub для
# автоматизации подходит GitHub Actions.
#
# 21. Как упомянуть другого пользователя в комментарии к Issue?
#
# Написать @username в комментарии. GitHub создаст упоминание, и
# пользователь обычно получит уведомление в зависимости от своих
# настроек.
#
# 22. Как запросить у автора Issue дополнительные данные или
# уточнения?
#
# Оставить комментарий с конкретными вопросами: как воспроизвести
# проблему, какая версия используется, что ожидалось и что произошло.
# При необходимости упомянуть автора через @username.
#
# 23. Что делать, если Issue неактуально или его нужно объединить с
# другим?
#
# Неактуальную задачу можно закрыть с пояснением и причиной Not
# planned. Если это дубликат, нужно сослаться на основное Issue, при
# необходимости добавить метку duplicate и закрыть повторную задачу.
# История двух Issues при этом не объединяется.
#
# 24. Как использовать шаблоны для создания Issues?
#
# Добавить шаблоны .md или формы .yml в папку .github/ISSUE_TEMPLATE
# основной ветки. При создании Issue пользователь выбирает подходящий
# шаблон и заполняет предусмотренные поля.
#
# 25. Что такое Linked Issues и как создать связь между задачами?
#
# Это связанные задачи. Для простой ссылки достаточно указать #номер
# Issue в описании или комментарии. Для структурной связи можно
# создать Sub-issue, а для зависимости — выбрать Relationships → Mark
# as blocked by или Mark as blocking.
#
# 26. Какие метрики (например, время выполнения) можно отслеживать с
# помощью Issues?
#
# Можно отслеживать число открытых и закрытых задач, время от создания
# до закрытия, количество выполненных задач за период и прогресс
# milestone. В Projects и внешней аналитике можно строить
# дополнительные отчёты.
#
# 27. Какие best practices рекомендуются при работе с Issues в
# команде?
#
# Давать задачам понятные названия, описывать ожидаемый результат, не
# смешивать несколько независимых проблем в одной задаче. Полезно
# использовать единые метки, назначать ответственных, связывать PR с
# Issue, избегать дубликатов и закрывать задачи с понятным итогом.
