# ## Введение в PyPy
#
# 13. Чем PyPy отличается от CPython?<br>
# *Ответ:* PyPy это альтернативная реализация Python. Ключевое отличие: PyPy
# использует JIT-компиляцию. Он находит часто выполняемые участки кода и
# компилирует их в машинный код, тогда как CPython компилирует код в байт-код и
# интерпретирует его. За счёт этого PyPy может сильно ускорять программы на
# чистом Python, но величина ускорения зависит от кода: на циклах с числовыми
# вычислениями оно бывает многократным (в нашем тесте порядка десятков раз), на
# коротких скриптах и на коде, где основное время тратится в библиотеках на C,
# выигрыша может почти не быть. PyPy также обычно потребляет больше памяти и
# отстаёт от CPython по поддерживаемым версиям языка.
#
# 14. Почему PyPy подходит не для всех проектов на Python?<br>
# *Ответ:* Главная причина в C-расширениях. Многие популярные библиотеки
# (NumPy, pandas, SciPy и др.) написаны на C и работают через C API CPython.
# PyPy устроен иначе и поддерживает C API только через слой совместимости
# (cpyext), который медленнее и работает не со всеми библиотеками, поэтому
# проект, зависящий от таких пакетов, может работать медленно или не
# запуститься. Кроме того, на коротких программах JIT не успевает «прогреться»,
# а потребление памяти выше.
#
# 15. Где можно скачать PyPy?<br>
