# 5. Как установить пакеты внутрь виртуального окружения venv и conda?
# 1) source venv/bin/activate (обязательно надо сначало активировать venv)
# pip install pandas (вместо pandas можно любой пакет)
# 2) то же самое с conda:
# conda activate SENATOROV
# conda install pandas
#
# 6. Что делают эти команды?
# pip freeze > requirements.txt
# conda env export > environment.yml
# 1) Первая команда сохраняет пакеты pip в requirements.txt
# 2) Вторая команда сохраняет все окружение conda в environment.yml
#
