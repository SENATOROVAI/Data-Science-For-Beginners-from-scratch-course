# # Квиз 1. Алгоритм сдачи домашних заданий

# ## Основные вопросы

# **1.** Зачем нужна кнопка History и какие функции появляются при нажатии правой кнопкой мыши на коммит?

# **Ответ:** Кнопка History в GitHub Desktop показывает историю коммитов текущей ветки: кто, когда и что изменил. Чтобы принять домашку, в GitHub Desktop нажимают Fetch origin и смотрят History — там появляются новые коммиты. Если нажать на коммит правой кнопкой мыши, открывается меню: View on GitHub (открыть коммит на сайте, чтобы взять ссылку), создать ветку от коммита (Create Branch from Commit), скопировать SHA коммита, откатить коммит (Revert Changes in Commit), перенести его в другую ветку (Cherry-pick).

# **1.1.** Где взять ссылку на коммит? Куда её отправлять?

# **Ответ:** Ссылку на коммит берут в GitHub Desktop: вкладка History → правая кнопка мыши по коммиту → View on GitHub. Откроется страница коммита, ссылку копируют из адресной строки браузера и отправляют в чат в Telegram, обязательно написав «коммит отдал».

# **2.** Что такое файл лога?

# **Ответ:** Файл лога — это файл, в котором записывают дату урока и ключевые моменты: что запомнили. Важное выделяют средствами markdown.

# **2.1.** Когда нужно его пушить?

# **Ответ:** Лог нужно пушить после выполнения работы, вместе с коммитом по заданию, чтобы запись о выполненном уроке попала на GitHub.

# **3.** Что такое интерпретатор?

# **Ответ:** Интерпретатор — программа, которая читает код на Python и выполняет его построчно. От выбранного интерпретатора зависят версия Python и набор доступных библиотек.

# **4.** Где можно выбрать интерпретатор?

# **Ответ:** В VS Code: Cmd+Shift+P, команда «Python: Выбор интерпретатора» (Python: Select Interpreter), либо нажать на название окружения в нижней строке состояния. Для ноутбука ядро выбирают кнопкой «Выбрать ядро» справа вверху. В видео выбирают интерпретатор Anaconda.

# **5.** Что такое модуль?

# **Ответ:** Модуль — это файл с расширением .py с кодом (функции, классы, переменные), который можно запустить или импортировать в другой код командой import.

# **6.** Как создать и отправить коммит?

# **Ответ:** В GitHub Desktop: в поле сообщения пишут имя коммита и нажимают Commit. Перед отправкой проверяют, что все секции проверки зелёные (ошибки устранены), и нажимают Push origin. Тот же результат даёт терминал: `git add файл`, `git commit -m 'docs: add quiz answers'`, `git push`.

# **7.** Как убедиться, что коммит отправлен и находится на GitHub?

# **Ответ:** В GitHub Desktop: вкладка History → правая кнопка по коммиту → View on GitHub. Если коммит открывается на сайте GitHub, значит он отправлен. Также `git status` покажет, что ветка не отстаёт от origin.

# **8.** Какая команда показывает, что код не прошёл проверки на ошибки?

# **Ответ:** `pre-commit run --all-files` — запускает все проверки из файла .pre-commit-config.yaml и показывает, какие из них не прошли (Failed). Её используют, когда коммит не отправляется из-за ошибок.

# **8.1.** Перечислите линтеры, которые используются для проверки кода, и кратко охарактеризуйте каждый.

# **Ответ:** Pylint — общий анализ кода: ошибки, плохой стиль, неиспользуемые переменные, ставит оценку из 10. Flake8 — проверяет соответствие PEP 8 и простые ошибки. Mypy — проверяет типы данных (аннотации типов). Pydocstyle — проверяет оформление докстрингов (описаний модулей, функций и классов).

# **9.** Как узнать, какой именно линтер не прошёл проверку?

# **Ответ:** В выводе pre-commit у каждой проверки есть название и статус Passed или Failed — по нему видно, какой линтер не прошёл, а под ним идёт список ошибок с файлом и строкой. В VS Code то же видно на панели Problems: у каждой ошибки указан источник (Pylint, mypy и т.д.).

# **10.** Видит ли линтер Pylint markdown?

# **Ответ:**Нет. Pylint проверяет только Python-код (в ноутбуке — кодовые ячейки), markdown-ячейки он не анализирует.

# **11.** Могут ли номер ячейки в терминале и номер ячейки в VS Code отличаться? В каком случае?

# **Ответ:** Да, могут. Линтер не считает markdown-ячейки, поэтому номер ячейки в терминале и номер в VS Code могут расходиться.

# **12.** Где посмотреть номер ячейки в VS Code?

# **Ответ:** В VS Code внизу, в строке состояния, написано «Ячейка N из M» для текущей выбранной ячейки.

# **13.** В каком формате .ipynb отправляется на GitHub? При чём здесь JSON?

# **Ответ:** В формате JSON: .ipynb — это текстовый файл, в котором ячейки (тип, исходный текст, вывод) и метаданные хранятся в виде JSON-структуры. GitHub умеет отображать такой файл как ноутбук.

# **14.** Где посмотреть, в какой ячейке ошибка?

# **Ответ:** Номер ячейки с ошибкой указан в выводе линтера в терминале и на панели Problems; в самом ноутбуке упавшая ячейка показывает traceback в своём выводе.

# **15.** Как запустить терминал?

# **Ответ:** Через меню Terminal → New Terminal или сочетанием клавиш Ctrl+`

# **16.** Что такое линтер?

# **Ответ:** Линтер — программа, которая анализирует код без его запуска и находит ошибки, нарушения стиля и подозрительные места.

# **17.** На какой сайт нужно вставлять код ошибки, если она связана с Pylint?

# **Ответ:** Код ошибки Pylint вставляют на сайт Pylint: там по коду ошибки есть объяснение, что она значит и как её исправить. Если лень заходить на сайт, ошибку можно найти в чате help me.

# **18.** Секция pydocstyle в большинстве случаев закрывается автоматически после исправления ошибок в каком линтере?

# **Ответ:** Pylint. После исправления ошибок Pylint секция pydocstyle в большинстве случаев закрывается автоматически.

# **19.** Что такое описание модуля? Должно ли оно отражать содержимое модуля?

# **Ответ:** Описание модуля — это многострочный комментарий (докстринг) в самом начале файла, который кратко объясняет, для чего нужен модуль. В видео ошибки секции pydocstyle устраняют именно добавлением описания модуля. Да, описание должно отражать содержимое модуля.

# **20.** С какой git-команды начинается утро программиста?

# **Ответ:** Утро программиста начинается с команд Fetch origin и pull

# **21.** После внесения изменений в файлы кнопка «Open in Visual Studio Code» в GitHub Desktop пропадает. Как ещё можно открыть VS Code из GitHub Desktop?

# **Ответ:** Из меню GitHub Desktop: Repository → Open in Visual Studio Code, либо файл правой мышью и выбрать в вс коде

# ## Stash

# **22.** Что такое stash? Объясните концепцию в общих чертах.

# **Ответ:** Stash — временное хранилище в git, черновик коммита

# **22.1.** Как сохранить изменения в stash?
#
# - git-команда:
# - кнопка в VS Code:

# **Ответ:** - git stash или в вс коде через три точки

# **22.2.** Как восстановить stash?
#
# - git-команда:

# **Ответ:** - git-команда: `git stash pop` — применяет последний stash и удаляет его из списка; `git stash apply` — применяет, но оставляет запись в списке.

# **22.3.** Чем stash отличается от коммита? Когда лучше сохранить изменения в stash, а когда — закоммитить?

# **Ответ:** Коммит — это постоянная запись в истории ветки, которую видят другие после push. Stash — временная локальная заначка черновик коммита

# **22.4.** Как просмотреть список сохранённых stash?
#
# - git-команда:

# **Ответ:** - git-команда: `git stash list` — показывает список сохранённых stash

# **22.5.** Как удалить stash? Приведите команды для удаления отдельной записи и всех сразу.
#
# - git-команда:

# **Ответ:** - git-команда: `git stash drop stash@{0}` — удалить одну запись (номер смотрим в `git stash list`); `git stash clear` — удалить все записи сразу.

# **22.6.** Приведите практические примеры использования stash — краткие сценарии, где он помогает.

# **Ответ:** 1) Срочно нужно переключиться на другую ветку, а текущая работа не готова — прячем в stash, переключаемся, потом возвращаем. 2) Перед `git pull` в рабочей папке есть незакоммиченные изменения, которые мешают — прячем, делаем pull, возвращаем. 3) Изменения случайно сделаны не в той ветке — прячем, переключаемся на нужную ветку и применяем там.

# ## Конфликты

# **23.** Где увидеть, что в файлах есть конфликт?

# **Ответ:** В VS Code конфликтные файлы отображаются на вкладке Source Control в разделе Merge Changes, или кошко не даст коммит отдать выйдет окошко

# **23.1.** Когда он возникает?

# **Ответ:** Конфликт возникает, когда одну и ту же часть файла изменили по-разному

# **24.** Как разрешить конфликт в файлах?

# **Ответ:** Открыть файл с конфликтом и для каждого конфликтного места выбрать вариант: Accept Current Change (оставить локальное), Accept Incoming Change (взять пришедшее), Accept Both Changes (оставить оба) или отредактировать вручную, удалив маркеры конфликта. Затем сохранить файл и завершить слияние

# **25.** Выберите правильное утверждение:
#
# - а) зелёное — то, что пришло с GitHub, синее — локальные изменения;
# - б) синее — то, что пришло с GitHub, зелёное — локальные изменения.

# **Ответ:** Верно утверждение б): синее — то, что пришло с GitHub (Incoming), зелёное — локальные изменения (Current).

# **26.** Если мы работаем в одном файле, можно ли принять pull после того, как спрятали свои изменения в stash?

# **Ответ:** Да. После git stash рабочая папка чистая, поэтому pull проходит без конфликта с локальными изменениями.

# **26.1.** Что может произойти, если восстановить stash после принятия pull?

# **Ответ:** После pull файл может измениться, и при возврате stash git попробует наложить спрятанные изменения на новую версию файла. Если изменения затронули те же строки, возникнет конфликт, который придётся разрешать вручную.

# **27.** Сколько способов разрешения конфликтов показано в видео? Укажите число и перечислите способы.

# **Ответ:** Показано три способа: 1) Accept Current Change — оставить свой (локальный) вариант; 2) Accept Incoming Change — принять изменения, пришедшие с GitHub; 3) Accept Both Changes — оставить оба варианта. Чаще всего берут то, что пришло с GitHub (Incoming).

# **28.** Что делает кнопка Complete Merge?

# **Ответ:** Кнопка Complete Merge завершает слияние после того, как все конфликты разрешены: фиксирует результат в коммите.

