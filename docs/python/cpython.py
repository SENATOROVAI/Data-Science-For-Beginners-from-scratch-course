# 10. (опционально) Как работает интерпретатор CPython при выполнении кода?
# Подготовительный этап(один раз):
# 10.1. Исходный код СPython, написанный на С, компилируется компилятором (Clang) и линкуется в исполняемый файл python.
#
# Во время выполнения программы:
# 10.2 Интерпретатор CPython читает исходный .py
# 10.3 Выполняет лексический анализ, синтаксический анализ (парсинг) и строит AST (абстрактное синтаксичекое дерево)
# 10.4 Компилирует AST в байткод Python.
# 10.5 Python Virtual Machine последовательно интерпретирует инструкции байткода.
# 10.6 Для выполнения каждой инструкции используется соответсвующие функции СPython, написанный на языке С, которые взаимодействуют с памятью,ОС и процессором.
