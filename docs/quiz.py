# 4. Что такое PEP 8? (подсказка)
#
# PEP 8 (Python Enhancement Proposal 8) — это официальный стандарт оформления Python-кода, который определяет правила написания чистого, читаемого и единообразного кода.
# Основные правила PEP 8:
# 1. Отступы — 4 пробела для каждого уровня вложенности.
# 2. Длина строки — рекомендуется не более 79 символов.
# 3. Имена переменных — snake_case (например, total_amount).
# 4. Имена классов — CamelCase (например, CreditRiskModel).
# 5. Пробелы — правильное использование пробелов вокруг операторов.
# 6. Импорты — размещаются в начале файла и группируются по категориям.

# 4.1. Проверяют ли линтеры соблюдение PEP 8?
#
# Да, линтеры проверяют соблюдение PEP 8 и помогают поддерживать единый стиль и читаемость Python-кода.

# 4.2. Какая нотация используется для именования переменных? (ответ на стр. 85–95: https://t.me/c/1937296927/1/16676)
#
# Змеиный регистр (snake_case) разделяет слова символом подчеркивания,
# который напоминает ползущую между словами змею. В этом случае все
# буквы записываются в нижнем регистре, а константы часто записываются
# в верхнем змеином регистре (UPPER_SNAKE_CASE).
# Верблюжий регистр (camelCase) — слова записываются в нижнем регистре,
# но второе и следующие слова начинаются с заглавной. Эта схема в большин
# стве случаев подразумевает, что первое слово начинается с буквы нижнего
# регистра. Буквы верхнего регистра напоминают верблюжьи горбы.
# Схема Pascal (PascalCase) — названа так, потому что применяется в языке
# программирования Pascal; аналогична схеме верблюжьего регистра, но первое
# слово в ней тоже начинается с заглавной.

