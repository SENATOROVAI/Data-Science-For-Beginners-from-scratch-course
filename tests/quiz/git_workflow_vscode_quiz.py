# ## Stash

# **22. Что такое stash? Объясните концепцию в общих чертах.**

# Stash («тайник») — временное хранилище для незакоммиченных изменений. Команда убирает изменения из рабочей папки (файлы возвращаются к состоянию последнего коммита) и откладывает их в отдельный стек. Потом их можно вернуть обратно в ту же или другую ветку. Это удобно, когда нужно срочно переключиться на другую задачу, а коммитить незаконченную работу не хочется.

# **22.1. Как сохранить изменения в stash?**
#
# - git-команда (подсказка):
# - кнопка в VS Code:

# - git-команда: `git stash` или с подписью `git stash push -m "описание"`. Чтобы сохранить и новые (неотслеживаемые) файлы: `git stash -u`.
# - кнопка в VS Code: **Source Control** → `...` (More Actions) → **Stash** → **Stash**. В GitHub Desktop: правый клик по списку изменений → **Stash all changes**.

# **22.2. Как восстановить stash (подсказка)?**
#
# - git-команда (подсказка):

# - `git stash pop` — вернуть последние изменения и удалить запись из stash;
# - `git stash apply` — вернуть, но оставить запись в stash;
# - `git stash apply stash@{2}` — вернуть конкретную запись.
#
# В VS Code: **Source Control** → `...` → **Stash** → **Pop Latest Stash**.

# **22.3. Чем stash отличается от коммита? Когда лучше сохранить изменения в stash, а когда — закоммитить?**

# - **Коммит** — постоянная точка в истории ветки: с сообщением, хранится в репозитории и отправляется на GitHub.
# - **Stash** — временная «полка» только на вашем компьютере: не попадает в историю, не пушится, его легко забыть или потерять.
#
# Stash — когда работа не закончена и нужно ненадолго переключиться (сменить ветку, сделать pull). Коммит — когда изменения логически завершены и их нужно сохранить надолго и отправить.

# **22.4. Как просмотреть список сохранённых stash?**
#
# - git-команда (подсказка):

# `git stash list`. Записи выглядят так: `stash@{0}: On main: описание`. Посмотреть содержимое записи: `git stash show -p stash@{0}`.

# **22.5. Как удалить stash? Приведите команды для удаления отдельной записи и всех сразу.**
#
# - git-команда (подсказка):

# - Одна запись: `git stash drop stash@{0}` (без аргумента удаляется последняя).
# - Все записи сразу: `git stash clear`.

# **22.6. Приведите практические примеры использования stash — краткие сценарии, где он помогает.**

# 1. Начали работу, а нужно забрать изменения с GitHub: `git stash` → `git pull` → `git stash pop`.
# 2. Случайно начали правки в `main`, а не в ветке задания: `git stash` → `git switch task/...` → `git stash pop` (именно так GitHub Desktop предлагает «Bring my changes» при переключении веток).
# 3. Срочно нужно исправить ошибку в другой ветке: спрятали незаконченную работу, исправили, вернулись и достали изменения.
# 4. Хотим проверить, работал ли код до наших правок: спрятали правки, запустили, вернули.

# ## Конфликты

# **23. Где увидеть, что в файлах есть конфликт?**

# - В VS Code: в **Source Control** появляется раздел **Merge Changes**, файлы помечены буквой `!`/`C`; в самом файле подсвечены блоки между маркерами `<<<<<<<`, `=======`, `>>>>>>>`.
# - В GitHub Desktop: окно с сообщением о конфликтах и списком файлов.
# - В терминале: `git status` показывает `Unmerged paths` и `both modified`.

# **23.1. Когда он возникает?**

# Когда одни и те же строки одного файла изменены по-разному в двух местах (например, локально и на GitHub, или в двух ветках), и Git не может сам решить, какую версию оставить. Случается при `git pull`, `git merge`, `git rebase`, `git stash pop`.

# **24. Как разрешить конфликт в файлах?**

# 1. Открыть файл с конфликтом.
# 2. Для каждого блока выбрать: **Accept Current Change** (оставить локальное), **Accept Incoming Change** (оставить пришедшее), **Accept Both Changes** (оставить оба) — или отредактировать вручную, удалив маркеры `<<<<<<<`, `=======`, `>>>>>>>`.
# 3. Сохранить файл и добавить его в индекс (`+` в Source Control или `git add <файл>`).
# 4. Сделать коммит.
#
# Для удобства можно открыть **Resolve in Merge Editor** и в конце нажать **Complete Merge**.

# **25. Выберите правильное утверждение:**
#
# а) зелёное — то, что пришло с GitHub, синее — локальные изменения;
# б) синее — то, что пришло с GitHub, зелёное — локальные изменения.

# **б)** — синее (Incoming Change) пришло с GitHub, зелёное (Current Change) — локальные изменения.

# **26. Если мы работаем в одном файле, можно ли принять pull после того, как спрятали свои изменения в stash?**

# Да. После `git stash` рабочая папка чистая, поэтому `git pull` пройдёт без помех.

# **26.1. Что может произойти, если восстановить stash после принятия pull?**

# Если пришедшие с GitHub изменения затронули те же строки, что и спрятанные, при `git stash pop` возникнет **конфликт**. Его нужно разрешить как обычный конфликт. Запись при этом остаётся в stash, после разрешения её удаляют вручную `git stash drop`. Если строки разные, изменения просто объединятся.

# **27. Сколько способов разрешения конфликтов показано в видео? Укажите число и перечислите способы.**

# Три способа:
# 1. Кнопки над конфликтным блоком прямо в файле: Accept Current / Accept Incoming / Accept Both Changes.
# 2. Merge Editor (**Resolve in Merge Editor**) с тремя панелями и кнопкой **Complete Merge**.
# 3. Ручное редактирование файла с удалением маркеров конфликта.

# **28. Что делает кнопка Complete Merge?**

# Завершает разрешение конфликта в Merge Editor: сохраняет итоговую версию файла и отмечает конфликт как решённый (добавляет файл в индекс, как `git add`). После этого остаётся сделать коммит.

