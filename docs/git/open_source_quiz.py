# 10.2 Что такое файл .gitignore?
# - файл, который содержит список файлов и каталогов, которые Git должен
#   игнорировать и не добавлять в репо, такие как .venv, .env, __pycache__,
#   большие датасеты. Он используется, чтобы не хранить временные файлы,
#   зависимости, конфиденциальные и большие данные. Он действует только на
#   неотслеживаемые файлы, которые не попали в индекс.
