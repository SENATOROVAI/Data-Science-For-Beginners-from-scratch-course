# ## Дополнительные вопросы

# **1.** Какая команда конвертирует файл из .ipynb в .py?

# **Ответ:** `jupyter nbconvert --to script имя_файла.ipynb` — создаёт из ноутбука обычный файл .py.

# **2.** Что такое пакетный менеджер? Каким вы пользуетесь — conda или pip? Какой лучше использовать в data science?

# **Ответ:** Пакетный менеджер — программа для установки, обновления и удаления библиотек и их зависимостей. pip ставит пакеты из PyPI и работает только с Python-пакетами. conda умеет ставить и пакеты, и отдельные окружения, в том числе не только Python-библиотеки (например, нужные системные библиотеки и разные версии самого Python). В data science обычно удобнее conda: она лучше справляется с тяжёлыми научными библиотеками.

# **3.** Почему расширение .py лучше, чем .ipynb?

# **Ответ:** Файл .py — обычный текстовый файл: он компактнее, в git видны только изменения кода (а не JSON с выводом ячеек и метаданными), его проще проверять линтерами и запускать из терминала. Ноутбук .ipynb удобен для экспериментов, но тяжелее для ревью и контроля версий.

# **4.** Что такое PEP 8?

# **Ответ:** PEP 8 — официальное руководство по стилю кода на Python: как называть переменные, как оформлять отступы, сколько символов допускается в строке и так далее. Нужен, чтобы код был единообразным и читаемым.

# **4.1.** Проверяют ли линтеры соблюдение PEP 8?

# **Ответ:** Да, часть линтеров (например, flake8, pycodestyle, а также Pylint) проверяют соблюдение правил PEP 8.

# **4.2.** Какая нотация используется для именования переменных?

# **Ответ:** Для переменных и функций используется snake_case: слова пишутся строчными буквами и разделяются подчёркиванием, например user_name. Для классов используется CapWords, для констант — UPPER_CASE.

# **4.3.** Может ли имя переменной состоять из одного символа, например из подчёркивания _ ?

# **Ответ:** Да, это допустимо: имя переменной может состоять из одного символа, например из подчёркивания _. По соглашению _ — имя для заведомо ненужного значения.

# **4.4.** Зачем и где используется подчёркивание _ ?

# **Ответ:** Подчёркивание _ — имя для заведомо ненужного значения, например в цикле for _ in range(3). Также _ используется как разделитель разрядов в больших числах (1_000_000) и как префикс для «внутренних» имён.

# **4.5.** Допустимо ли по PEP 8 имя переменной из одной буквы?

# **Ответ:** Формально PEP 8 не запрещает короткие имена, но не рекомендует имена из одной буквы

