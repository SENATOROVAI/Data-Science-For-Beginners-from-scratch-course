# Что делает команда git stash?
# Сохраняет незакоммиченные изменения во временное хранилище (стэш) и
# очищает рабочую директорию.

# Как просмотреть список всех сохранённых изменений (стэшей)?
# В терминале: git stash list. В GitHub Desktop: Stashed Changes → View.

# Какая команда применяется для использования верхнего стэша?
# git stash apply (или git stash pop, если стэш нужно сразу удалить).

# Как применить конкретный стэш по его номеру?
# Сначала посмотреть номера командой git stash list (stash@{0}, stash@{1}).
# Затем выполнить git stash apply stash@{N}, где N — номер стэша.
# В GitHub Desktop: выбрать стэш (View) и нажать Restore.

# Чем отличается команда git stash apply от git stash pop?
# apply применяет изменения из стэша, но оставляет сам стэш в списке.
# pop применяет изменения и сразу удаляет этот стэш из списка.

# Что делает команда git stash drop?
# Удаляет стэш из списка (по умолчанию верхний, можно указать номер).

# Как полностью очистить все сохранённые стэши?
# Командой git stash clear: она удаляет сразу все стэши.

# В каких случаях удобно использовать git stash?
# Чтобы быстро переключить ветку, не коммитя незаконченную работу, и
# перед pull или merge, когда рабочая директория должна быть чистой.
# Также стэш удобен как черновик: изменения можно временно убрать и вернуть.

# Что произойдёт, если выполнить git stash pop, но в проекте есть
# конфликтующие изменения?
# Git применит изменения и поставит в файлах маркеры конфликта, но сам
# стэш не удалит: он останется в списке. Конфликт нужно разрешить вручную,
# а затем удалить стэш командой git stash drop.

# Можно ли восстановить удалённый стэш после выполнения git stash drop?
# Да, пока он не удалён сборщиком мусора. При drop Git выводит хеш стэша;
# восстановить можно командой git stash apply <хеш>. Если хеш потерян,
# его ищут через git fsck --unreachable | grep commit.

# Что делает команда git stash push -m "NAME_STASH"
# Сохраняет изменения в новый стэш с указанным именем. Параметр -m
# задаёт имя (сообщение) стэша. Старая команда git stash save устарела,
# вместо неё используют git stash push -m.

# Что делает команда git stash apply "NUMBER_STASH"
# Применяет стэш с указанным номером (stash@{N}) к рабочей директории, сам
# стэш остаётся в списке.

# Что делает команда git stash pop "NUMBER_STASH"
# Применяет стэш с указанным номером и сразу удаляет его из списка.

