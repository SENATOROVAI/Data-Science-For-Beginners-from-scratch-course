# 1. Что такое CPython и чем он отличается от Python?
# - CPython - это наиболее распространенная реализация Python с компилятором,
#   написанная на С и компилируется С-компилятором.
# - CPython используется для выполнения большинства Python-программ.
# - Это не ЯП это реализация Python на языке программирования C.
# - Реализация исполняет байт-код, созданный интерпретатором.
# - Python описывает синтаксис, а CPython интерпретирует код по этим правилам.
#
# 2. Ответьте на вопрос с изображения (ключевые различия Python и CPython).
# - Python - язык программирования высокого уровня, концепция, которая
#   требует реализации и не зависит от языка реализации. Он описывает
#   for, if, функции.
# - CPython - официальная реализация Python, написанная на С: программа,
#   исполняющая байт-код Python. Он интерпретирует for, if, функции и
#   выполняет их.
#
# 3. Сколько существует реализаций Python и какая из них самая популярная?
