# # CPython и PyPy
#
# ## Теоретические вопросы
#
# ### 1. Что такое CPython и чем он отличается от Python?
#
# Python — это язык программирования: его синтаксис и правила.
# CPython — самая распространённая реализация Python, написанная в основном на C.
# Она принимает Python-код, компилирует его в байт-код и выполняет этот байт-код
# в виртуальной машине CPython.
#
# ### 2. В чём различие Python и CPython?
#
# Python — это сам язык: правила, конструкции `if`, `for`, функции, классы и
# другие элементы синтаксиса. CPython — конкретная программа, которая реализует
# эти правила и выполняет Python-код. Поэтому Python можно реализовать не только
# как CPython, но и другими способами, например PyPy.
#
# ### 3. Сколько существует реализаций Python и какая самая популярная?
#
# Единого точного количества реализаций Python нет: существуют разные проекты.
# Примеры пяти реализаций: CPython, PyPy, Jython, IronPython и MicroPython.
# Самая распространённая реализация — CPython.
#
# ### 4. На каком языке написан CPython?
#
# CPython написан в основном на языке C.
#
# ### 5. Кто создал CPython? (опционально)
#
# Первоначальную реализацию Python, которая стала CPython, создал Гвидо ван
# Россум. Сейчас CPython развивается сообществом Python Core Developers.
#
# ### 6. Почему Python считается быстрым, несмотря на то что это интерпретируемый язык?
#
# Сам CPython во многих вычислительных задачах медленнее компилируемых языков.
# Но разработка на Python обычно идёт быстрее, а тяжёлые операции часто
# выполняются в оптимизированных библиотеках, написанных на C, C++ или других
# низкоуровневых языках. Поэтому на практике Python может давать хорошую
# производительность при использовании таких библиотек.
#
# ### 7. Укажите путь к интерпретатору CPython на вашем компьютере
#
# Команды для проверки на Lubuntu:
#
# ```bash
# which python3
# python3 -c "import platform; print(platform.python_implementation())"
# ```
#
# Результат на моём компьютере:
#
# ```text
# /usr/bin/python3
# CPython
# ```
#
# ### 8. Что содержится в папке Include в CPython?
#
# В каталоге `Include` находятся заголовочные файлы C с расширением `.h`.
# Они содержат объявления структур, функций, типов и макросов, которые
# используются внутренними компонентами CPython и его C API.
#
# ### 9. Где найти исходный код CPython?
#
# Исходный код находится в официальном репозитории:
#
# https://github.com/python/cpython
#
# Заголовочные файлы находятся в каталоге:
#
# https://github.com/python/cpython/tree/main/Include
#
# ### 10. Как работает CPython при выполнении кода? (опционально)
#
# Упрощённо процесс выглядит так:
#
# 1. CPython читает исходный Python-код.
# 2. Код разбирается, строится внутреннее представление программы.
# 3. CPython компилирует код в Python bytecode.
# 4. Виртуальная машина CPython выполняет инструкции байт-кода.
# 5. Для многих операций вызываются функции реализации CPython, написанные на C.
#
# ## Запуск файла с помощью CPython
#
# ### 11. Какая команда используется для запуска файла с помощью CPython?
#
# В Lubuntu используется:
#
# ```text
# python3 script.py
# ```
#
# В Linux команда `python3` обычно указывает на установленный Python 3.
#
# ### 12. Можно ли запускать текстовые файлы через интерпретатор Python? Почему?
#
# Да. Расширение файла само по себе не определяет, можно ли выполнить его через
# интерпретатор. Если содержимое текстового файла является корректным
# Python-кодом, CPython может прочитать и выполнить его.
#
# ### 13. Как указать путь к интерпретатору и к файлу?
#
# Можно передать полный путь к интерпретатору, а после него полный путь к файлу:
#
# ```text
# /usr/bin/python3 /home/ata/пример/script.py
# ```
#
# ## Введение в PyPy
#
# ### 14. Чем PyPy отличается от CPython?
#
# PyPy — альтернативная реализация Python. Главное отличие для
# производительности — встроенный JIT-компилятор: часто выполняемые участки
# Python-кода во время работы программы могут компилироваться в машинный код.
#
# ### 15. Почему PyPy подходит не для всех проектов?
#
# PyPy хорошо совместим с обычным Python-кодом, но некоторые расширения,
# зависящие от CPython C API, могут работать иначе, медленнее или требовать
# слоя совместимости. Поэтому перед использованием PyPy нужно проверить
# совместимость библиотек конкретного проекта.
#
# ### 16. Где можно скачать PyPy?
#
# С официального сайта:
#
# https://pypy.org/download.html
#
# ## Установка и запуск PyPy
#
# ### 17. Как установить PyPy после скачивания?
#
# В Lubuntu можно скачать архив с официального сайта, распаковать в `~/tools`
# и запустить файл `bin/pypy3` из распакованной папки.
# Обычный CPython при этом остаётся установленным.
#
# ### 18. Как запустить файл с помощью PyPy?
#
# Например:
#
# ```text
# pypy3 example_pypy.py
# ```
#
# Если команда не добавлена в PATH, можно использовать полный путь к `bin/pypy3`.
#
# ### 19. Почему PyPy может выполнять код быстрее, чем CPython?
#
# PyPy использует JIT-компиляцию. Во время выполнения он определяет часто
# исполняемые участки программы и компилирует их в машинный код. Это особенно
# полезно для длительно работающего чистого Python-кода с большим количеством
# циклов. Для коротких программ или некоторых C-расширений ускорения может не
# быть.

