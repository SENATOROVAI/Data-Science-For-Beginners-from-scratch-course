# ## 6. Поддержание репозитория в актуальном состоянии
#
# **6. Как понять, что ваш форк устарел?**
#
# Форк не обновляется сам. На главной странице форка GitHub показывает строку вида **This branch is N commits behind <владелец>:main**: значит, в исходном репозитории есть коммиты, которых нет в форке. Локально это видно через `git fetch upstream` и `git log main..upstream/main`.
#
# **6.1. Как обновить форк?**
#
# В браузере: на странице форка нажать **Sync fork** → **Update branch**.
#
# Локально:
#
# ```bash
# git remote add upstream https://github.com/<владелец>/<репозиторий>.git
# git fetch upstream
# git switch main
# git merge upstream/main
# git push origin main
# ```
#
# Чтобы не делать это каждый раз вручную, можно настроить `main` на отслеживание `upstream/main`: `git branch --set-upstream-to=upstream/main main`.

