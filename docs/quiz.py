# 3.1. Какие практики принято соблюдать, чтобы issue закрывался
# автоматически?
#
# При создании pull request в его описании указывают ключевое слово и
# номер issue, например Closes #10 или Fixes #10.
# При создании коммита аналогичную запись добавляют в сообщение
# коммита, например Closes #10.
# Issue автоматически закрывается после попадания соответствующих
# изменений в основную ветку репозитория. Для автоматической привязки
# через описание PR целевой веткой должна быть ветка по умолчанию.
#
# 3.2. Как отклонить или закрыть pull request? Приложите скриншот
# того, где это находится на GitHub.
#
# Открыть репозиторий, перейти во вкладку Pull requests, выбрать
# нужный PR и на вкладке Conversation в нижней части страницы нажать
# кнопку Close pull request. Изменения не будут объединены с основной
# веткой.
#
# Скриншот: docs/images/image.png
#
# 3.3. Нужно ли создавать issue перед отправкой pull request?
#
# Нет, создание issue не является обязательным. Можно сразу открыть
# pull request. Однако для существенных изменений рекомендуется
# сначала создать или обсудить issue, чтобы согласовать задачу с
# сопровождающими проекта.
#
# 3.4. На какой вкладке можно посмотреть список изменений в pull
# request?
#
# На вкладке Files changed.
#
# 3.5. На какой вкладке находится страница обсуждения pull request?
#
# На вкладке Conversation.
#
# 4. Можно ли открыть pull request, если вы ничего не изменили в
# форке?
#
# Нет, если между сравниваемыми ветками нет различий, GitHub не
# позволит создать обычный pull request, поскольку нечего объединять.
#
# 4.1. Что нужно сделать, чтобы открыть pull request?
#
# Отправить изменения в свою ветку на GitHub, перейти в Pull requests
# → New pull request, выбрать исходную и целевую ветки, нажать Create
# pull request, указать заголовок и описание, затем подтвердить
# создание.
#
# 4.2. Что делать, если ваш форк устарел?
#
# Синхронизировать его с исходным репозиторием. Для этого открыть fork
# на GitHub, нажать Sync fork → Update branch. Также можно получить
# изменения из удалённого репозитория upstream с помощью Git.
#
# 4.3. Что делать, если в pull request есть конфликты слияния?
#
# Необходимо разрешить конфликты вручную или через кнопку Resolve
# conflicts, если она доступна. Затем сохранить исправления, создать
# коммит и обновить ветку PR. После разрешения всех конфликтов слияние
# станет возможным, если остальные проверки пройдены.
#
