# # Виртуальное окружение (venv и conda)
# ## Создание и активация окружения
# 1. Что делает команда python -m venv venv?
# *Ответ:* Создаёт папку venv с изолированным виртуальным окружением
#
# 2. Что делает каждая команда в списке ниже?
# *Ответ:*
#  pip list - выводит таблицу всех пакетов, установленных в текущем окружении, с версиями
#  pip freeze > requirements.txt - записывает установленные пакеты в файл requirements.txt
#  pip install -r requirements.txt - устанавливает все пакеты из файла requirements.txt
#
# 3. Что делает каждая команда в списке ниже?
# *Ответ:*
#     conda env list - показывает все окружения
#     conda create -n env_name python=3.5 - создаёт окружение env_name с заданной версией пайтон
#     conda env update -n env_name -f file.yml - обновляет существующее окружение env_name: доустанавливает и обновляет пакеты из file.yml
#     source activate env_name - активирует окружение. это устаревший синтаксис, сейчас пишут conda activate env_name
#     source deactivate - выходит из окружения. Тоже устарело, сейчас conda deactivate
#     conda clean -a - удаляет неиспользуемые архивы пакетов, кэш индекса и временные файлы, чтобы освободить место
