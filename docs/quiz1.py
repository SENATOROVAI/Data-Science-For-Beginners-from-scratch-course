# 22. Что такое stash? Объясните концепцию в общих чертах.
#
# Механизм позволяющий спрятать незакоммиченные
# изменения в рабочей директории, чтобы вернуть её
# в чистое состояние.
# Это полезно, когда нужно переключиться на другую задачу,
# но текущие изменения ещё не готовы для коммита.
#
# 22.1. Как сохранить изменения в stash?
#
# Git-команда: git stash push (или просто git stash).
#
# Git : Stash
#
# 22.2. Как восстановить stash
#
# git-команда (подсказка):
#
# git stash apply stash@{n}
#
# git stash pop - позволяет восстановить последний стэш и убрать его из списка
#
# где n - номер, полученный в списке git stash list
#
# 22.3. Чем stash отличается от коммита?
# Когда лучше сохранить изменения в stash, а когда - закоммитить?
#
# Stash - временное хранилище, не является частью истории ветки.
# Он не создаёт коммит и не фиксирует изменения в истории проекта.
# Коммит - постоянная фиксация изменений в истории ветки.
#
# 22.4. Как просмотреть список сохранённых stash?
#
# Git-команда: git stash list
#
# 22.5. Как удалить stash? Приведите команды для
# удаления отдельной записи и всех сразу.
#
# git-команда (подсказка):
#
# git stash drop stash@{n} - удаление одного конкретного, где n это номер
#
# git stash clear - удаление всех
#
# 22.6. Приведите практические примеры
# использования stash — краткие сценарии, где он помогает.
#
# Срочное переключение: Вы работаете над функцией,
# но вас просят срочно исправить баг в другой ветке.
# Вы делаете git stash, переключаетесь, исправляете баг,
# коммитите, возвращаетесь и делаете git stash pop.
#
