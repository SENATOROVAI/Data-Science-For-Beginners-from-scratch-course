# ### Вопрос 2
#
# **Что такое пакетный менеджер? pip или conda, что лучше для DS?**
#
# **Ответ:** Пакетный менеджер устанавливает и обновляет зависимости. pip ставит Python-пакеты; conda управляет ещё и окружениями и некоторыми не-Python-библиотеками. Для Data Science conda удобна при сложных научных зависимостях, но pip в виртуальном окружении тоже полностью подходит. В этой работе использован pip.
#
# ---
#
# ### Вопрос 3
#
# **Почему .py иногда удобнее, чем .ipynb?**
#
# **Ответ:** Файл .py содержит обычный текст Python-кода, поэтому его легче сравнивать в Git, ревьюить и использовать в автоматизированных проверках. .ipynb удобен для экспериментов, графиков и пошагового обучения — он не хуже во всех ситуациях.
#
# ---
#
# ### Вопрос 4
#
# **Что такое PEP 8?**
#
# **Ответ:** Официальное руководство по стилю Python-кода: отступы, пробелы, длина строк, именование и др. https://peps.python.org/pep-0008/
#
# ---
#
# ### Вопрос 4.1
#
# **Линтеры проверяют соблюдение PEP 8?**
#
# **Ответ:** Да, некоторые — например Flake8 и Pylint — проверяют часть стилевых правил PEP 8. Black автоматически форматирует код, но не является линтером.

# ### Вопрос 4.2
#
# **Какая нотация для названий переменных?**
#
# **Ответ:** По PEP 8 для обычных переменных и функций используется snake_case: например, total_price. Имена классов обычно используют CapWords (PascalCase).
#
# ---
#
# ### Вопрос 4.3
#
# **Может ли переменная называться одной буквой или _?**
#
# **Ответ:** Да. Например, x = 5; символ _ — допустимое имя и часто обозначает значение, которое намеренно не используется.
#
# ---
#
# ### Вопрос 4.4
#
# **Для чего используют подчёркивание _?**
#
# **Ответ:** В snake_case: total_price; для неиспользуемого значения: for _ in range(3); ведущий _ в имени — условный признак внутреннего использования; в числах 1_000_000 — разделитель разрядов.
#
# ---
#
# ### Вопрос 4.5
#
# **Разрешает ли PEP 8 переменную из одной буквы?**
#
# **Ответ:** Да, прямого запрета нет. Но имена l (маленькая латинская L), O (большая O) и I (большая i) в качестве однобуквенных переменных нежелательны, потому что легко путаются с цифрами 1 и 0. В остальных случаях важна понятность.

