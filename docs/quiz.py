# **6.** Где в VS Code находится git-клиент? Как в нём отправить коммит? Как принять домашнее задание?

# **Ответ:** в VS Code находится на вкладке Source Control три точки на левой панели. Чтобы принять домашнее задание, нужно нажать три точки (…) и выбрать кнопку Pull. Отправить коммит можно там же или в кошке

# **7.** Что такое Git? Он локальный? Можно ли в нём посмотреть историю изменений файлов и вернуться к любому коммиту?

# **Ответ:** Git — система контроля версий. Да, он работает локально: история хранится в папке .git на компьютере, а GitHub — отдельный удалённый сервис для хранения репозиториев. Да, в git можно посмотреть историю изменений файлов и вернуться к нужному коммиту

# **8.** Как вставить картинку в markdown?

# **Ответ:** В markdown-ячейке синтаксисом `![описание](путь_к_файлу_или_ссылка)`: картинка подтянется из файла в репозитории или из интернета.

# **9.** Где посмотреть длину строки в VS Code?

# **Ответ:** Длина строки видна в нижней строке состояния VS Code

# **10.** Как поменять тип ячейки с Python на Markdown?

# **Ответ:** Выбрать ячейку и в её правом нижнем углу нажать на язык (Python), затем выбрать Markdown; либо выйти из режима редактирования (Esc) и нажать M. Обратно в Python — клавиша Y.

# **11.** Как запустить сразу все ячейки в Jupyter?

# **Ответ:** Кнопкой Run All на верхней панели ноутбука.

# **12.** Как изменить размер картинки в Jupyter? Нужно ли для этого знать HTML?

# **Ответ:** В markdown-ячейке можно вставить картинку HTML-тегом с указанием размера

# **13.** Какое сочетание клавиш запускает ячейку с переходом к следующей?

# **Ответ:** Shift+Enter — запускает текущую ячейку и переходит к следующей.

# **14.** Как включить отображение номеров строк в Jupyter (Cell Line Numbers)?

# **Ответ:** Через палитру команд (Cmd+Shift+P) команда Notebook: Toggle Cell Line Numbers (или Toggle Line Numbers), либо клавишей L на выбранной ячейке.

# **15.** Что такое «Go To» и чем это полезно? Как сразу перейти к ячейке с ошибкой?

# **Ответ:** Go To — это навигатор по ячейкам. После проверки, когда линтер показал ошибку с номером ячейки, через Go To можно сразу перейти к ячейке с ошибкой.

# **16.** Как очистить вывод уже запущенных ячеек?

# **Ответ:** Кнопкой «Очистить все выходные данные» (Clear All Outputs) на верхней панели ноутбука.

# **17.** Как работать одновременно с несколькими файлами в VS Code? Что такое Split?

# **Ответ:** Файлы можно открыть рядом через разделение редактора (Split): кнопка Split Editor Right в правом верхнем углу вкладки, либо перетащить вкладку к краю окна. Тогда два файла видны одновременно.

# **18.** Каким сочетанием клавиш скрывается левая боковая панель?

# **Ответ:** Cmd+B — скрывает и показывает левую боковую панель.

# **19.** Кнопка с двумя листочками  — это наши локальные файлы?

# **Ответ:** Да. Кнопка с двумя листочками — это Explorer (Проводник): он показывает локальные файлы и папки открытого проекта на нашем компьютере.

