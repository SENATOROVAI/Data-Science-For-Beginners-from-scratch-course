# ### Вопрос 22
#
# **Что такое stash?**
#
# **Ответ:** git stash временно прячет незакоммиченные изменения из рабочей папки, чтобы можно было переключить ветку или принять новые изменения, а потом вернуть свою незавершённую работу.
#
# ---
#
# ### Вопрос 22.1
#
# **Как сохранить stash через Git и VS Code?**
#
# **Ответ:** Команда: `git stash push -u -m "незавершённая работа"` (опция `-u` также сохраняет новые, неотслеживаемые файлы; без неё они остаются в рабочей папке). В VS Code: Ctrl+Shift+P → Git: Stash (либо меню Source Control → Stash, если доступно).
#
# ---
#
# ### Вопрос 22.2
#
# **Как восстановить stash?**
#
# **Ответ:** git stash list → git stash apply stash@{0} (возвращает, но не удаляет stash) или git stash pop (возвращает и удаляет запись при успешном применении). В GitHub Desktop — Stashed Changes → Restore.
#
# ---
#
# ### Вопрос 22.3
#
# **Чем stash отличается от commit? Когда что применять?**
#
# **Ответ:** Commit создаёт постоянную точку в истории локальной ветки; stash — временно хранит незавершённые изменения вне истории ветки. Для готового логического результата нужен commit, для временного переключения задачи — stash.

# ### Вопрос 22.4
#
# **Как посмотреть список stash?**
#
# **Ответ:** Команда: git stash list.
#
# ---
#
# ### Вопрос 22.5
#
# **Как удалить отдельный stash или все stash?**
#
# **Ответ:** Отдельный: git stash drop stash@{0}. Все: git stash clear. Эти команды удаляют сохранённые изменения из stash, поэтому использовать их нужно осторожно.
#
# ---
#
# ### Вопрос 22.6
#
# **Примеры, когда помогает stash**
#
# **Ответ:** Нужно срочно перейти на другую ветку; нужно сделать git pull при незакоммиченных изменениях; хочешь ненадолго проверить другую версию проекта, не потеряв текущую работу.
